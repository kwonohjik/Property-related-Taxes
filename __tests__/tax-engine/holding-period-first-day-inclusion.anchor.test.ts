/**
 * 보유기간 초일 산입 anchor — 소득세법 §95④ 「자산의 취득일부터 양도일까지」
 *
 * §95④는 기간 계산의 특별규정이라 민법 §157 초일불산입이 적용되지 않는다(국기법 §4 단서).
 * - 재산46014-205(2002.12.18): §95·§104 보유기간은 「민법 제157조 초일불산입 규정에
 *   불구하고 그 기간의 초일을 산입」
 * - 국심1994경6005(1995.7.7): 「취득일인 '90.1.10을 보유기간 기산일로 보아 1년이 만료되는
 *   날은 '91.1.9이 되고 '91.1.10 … 양도한 이 건은 1년을 초과 보유」
 * - 집행기준 89-154-20: 「취득한 날의 초일을 산입하여 양도한 날까지로 계산」
 *
 * ⇒ N년은 취득일 응당일의 **전날**에 만료한다(민법 §160②). 만료연도에 해당일이 없으면
 *   그 달 말일(§160③).
 *
 * 종전 구현은 기산일을 취득일 다음날로 잡고 말일도 빼서(초일·말일 모두 불산입) 법정보다
 * 이틀 엄격했다 — 응당일 양도도 N년 미만으로 판정(리뷰 OH-21).
 * 계획서: docs/00-pm/one-house-exemption-fix.plan.md §1(유형 C)·§6.1 Q-1.
 */
import { describe, expect, it } from "vitest";
import { calculateHoldingPeriod } from "@/lib/tax-engine/tax-utils";

const years = (acq: string, transfer: string) =>
  calculateHoldingPeriod(new Date(acq), new Date(transfer)).years;

describe("HP-FD — §95④ 보유기간 초일 산입", () => {
  it("HP-FD-1 국심1994경6005: 1990-01-10 취득 → 1991-01-09(만료일) 양도 = 1년", () => {
    expect(years("1990-01-10", "1991-01-09")).toBe(1);
  });

  it("HP-FD-1 짝: 만료일 전날(1991-01-08) 양도 = 1년 미만", () => {
    expect(years("1990-01-10", "1991-01-08")).toBe(0);
  });

  it("HP-FD-2 §154① 2년: 2022-04-01 취득 → 2024-03-31 양도 = 2년", () => {
    expect(years("2022-04-01", "2024-03-31")).toBe(2);
  });

  it("HP-FD-2 짝: 2024-03-30 양도 = 1년", () => {
    expect(years("2022-04-01", "2024-03-30")).toBe(1);
  });

  it("HP-FD-3 응당일 양도(종전 구현이 N-1년으로 판정): 2014-01-01 → 2024-01-01 = 10년", () => {
    expect(years("2014-01-01", "2024-01-01")).toBe(10);
  });

  it("HP-FD-4 장특 10년 경계: 2014-01-01 → 2023-12-31 = 10년, 2023-12-30 = 9년", () => {
    expect(years("2014-01-01", "2023-12-31")).toBe(10);
    expect(years("2014-01-01", "2023-12-30")).toBe(9);
  });

  it("HP-FD-5 윤일 취득(§160③): 2020-02-29 → 2021-02-28 = 1년, 2021-02-27 = 0년", () => {
    expect(years("2020-02-29", "2021-02-28")).toBe(1);
    expect(years("2020-02-29", "2021-02-27")).toBe(0);
  });

  it("HP-FD-6 개월·일 분해: 2022-04-01 → 2024-03-31 = 2년 0월 0일", () => {
    expect(calculateHoldingPeriod(new Date("2022-04-01"), new Date("2024-03-31"))).toEqual({
      years: 2,
      months: 0,
      days: 0,
    });
  });
});
