/**
 * 조정대상지역 실제 데이터(REGULATED_REGIONS) anchor — 시점·지역별 교차검증
 *
 * 교재(양도소득세 2026) 변천표 + 주석 + 국토부 대책 사실을 고정한다.
 * 가정 코드(예시)는 "비택지/동지역" 등 판정 분기를 검증하기 위한 것으로,
 * region(앞 5자리) 매칭 + included/excluded 판정만 확인한다.
 */

import { describe, it, expect } from "vitest";
import { isRegulatedByBjdCode } from "@/lib/tax-engine/data/regulated-areas";

const reg = (code: string, date: string) => isRegulatedByBjdCode(code, date).isRegulated;

describe("조정대상지역 실제 데이터 anchor", () => {
  describe("서울", () => {
    it("강남구 — 줄곧 지정(2018·2024·2026)", () => {
      expect(reg("1168010100", "2018-01-01")).toBe(true);
      expect(reg("1168010100", "2024-01-01")).toBe(true); // 전역 해제기간에도 개별 유지
      expect(reg("1168010100", "2026-01-01")).toBe(true);
    });
    it("마포구(전역 폴백) — 전역기간 지정 / 해제기간 미지정 / 재지정", () => {
      expect(reg("1144010100", "2021-01-01")).toBe(true);
      expect(reg("1144010100", "2024-01-01")).toBe(false); // 2023.1.5~2025.10.15 해제
      expect(reg("1144010100", "2026-01-01")).toBe(true); // 2025.10.16 재지정
    });
  });

  describe("경기 — 재지정 그룹", () => {
    it("과천 — 2018 지정 / 2024 미지정 / 2026 재지정", () => {
      expect(reg("4129010100", "2018-06-01")).toBe(true);
      expect(reg("4129010100", "2024-01-01")).toBe(false);
      expect(reg("4129010100", "2026-01-01")).toBe(true);
    });
    it("성남 중원 — 2021 지정 / 2023 미지정(2022.11.14 해제) / 2026 재지정", () => {
      expect(reg("4113310100", "2021-01-01")).toBe(true);
      expect(reg("4113310100", "2023-06-01")).toBe(false);
      expect(reg("4113310100", "2026-01-01")).toBe(true);
    });
  });

  describe("경기 — 2022.9.26 해제 그룹", () => {
    it("평택 — 2021 지정 / 2022-12 미지정", () => {
      expect(reg("4122010100", "2021-01-01")).toBe(true);
      expect(reg("4122010100", "2022-12-01")).toBe(false);
    });
    it("양주 동지역 — 2021 지정 / 2022-12 미지정", () => {
      expect(reg("4163010100", "2021-01-01")).toBe(true);
      expect(reg("4163010100", "2022-12-01")).toBe(false);
    });
    it("양주 백석읍 — 2020.12.18 이전 지정 / 이후 제외", () => {
      expect(reg("4163025021", "2020-07-01")).toBe(true); // 6.19~12.17 전역
      expect(reg("4163025021", "2021-06-01")).toBe(false); // 12.18~ 제외
    });
  });

  describe("화성 — 동탄2택지만", () => {
    it("반송동(동탄2) 지정 / 비동탄2 미지정", () => {
      expect(reg("4159012700", "2020-01-01")).toBe(true); // 반송동
      expect(reg("4159010100", "2020-01-01")).toBe(false); // 화성 비동탄2(예시)
    });
  });

  describe("고양 — 택지지구 기간 토글", () => {
    it("삼송동 — 택지기간(2020-01) 지정", () => {
      expect(reg("4128111100", "2020-01-01")).toBe(true);
    });
    it("덕양 비택지 — 택지기간(2020-01) 미지정 / 전역기간(2021) 지정 / 최초전역(2018) 지정", () => {
      expect(reg("4128120100", "2020-01-01")).toBe(false); // 2019.11.8~2020.6.18 택지만
      expect(reg("4128120100", "2021-01-01")).toBe(true); // 2020.6.19~ 전역
      expect(reg("4128120100", "2018-06-01")).toBe(true); // 2017.8.3~2019.11.7 전역
    });
  });

  describe("김포 — 통진·대곶·월곶·하성면 제외", () => {
    it("통진읍 미지정 / 김포 동지역 지정 (2021)", () => {
      expect(reg("4157025021", "2021-06-01")).toBe(false); // 통진읍 리
      expect(reg("4157010100", "2021-06-01")).toBe(true); // 김포 동지역(예시)
    });
  });

  describe("인천 — 중구 을왕 / 강화·옹진 / 8개 구", () => {
    it("중구 을왕동 — 2020.12.18 이전 지정 / 이후 제외", () => {
      expect(reg("2811014900", "2020-08-01")).toBe(true); // 6.19~12.17
      expect(reg("2811014900", "2021-06-01")).toBe(false); // 12.18~ 제외
    });
    it("강화군·옹진군 — 상시 미지정", () => {
      expect(reg("2871010100", "2021-06-01")).toBe(false); // 강화
      expect(reg("2872010100", "2021-06-01")).toBe(false); // 옹진
    });
    it("연수구 — 2021 지정 / 2022-12 미지정(2022.11.14 해제)", () => {
      expect(reg("2818510100", "2021-06-01")).toBe(true);
      expect(reg("2818510100", "2022-12-01")).toBe(false);
    });
  });

  describe("파주 — 읍·면 제외(동 지역만), 2022.9.26 전체 해제", () => {
    it("문산읍 미지정 / 파주 동지역 지정 (2021)", () => {
      expect(reg("4148025021", "2021-06-01")).toBe(false); // 문산읍 리
      expect(reg("4148010100", "2021-06-01")).toBe(true); // 파주 동지역(예시)
    });
    it("파주 동지역 — 2020.11(지정 전) 미지정 / 2022-12(해제 후) 미지정", () => {
      expect(reg("4148010100", "2020-11-01")).toBe(false); // 2020.12.18 지정 전
      expect(reg("4148010100", "2022-12-01")).toBe(false); // 2022.9.26 해제 후
    });
  });

  describe("안성 — 시점별 제외 (6.19 일부 리 → 12.18 면 전체)", () => {
    it("죽산면 죽산리 — 2020-09(6.19~12.17) 제외", () => {
      expect(reg("4155040021", "2020-09-01")).toBe(false);
    });
    it("죽산면 칠장리(7리 아님) — 2020-09 지정 / 2021 제외(12.18 면 전체)", () => {
      expect(reg("4155040028", "2020-09-01")).toBe(true); // 6.19~12.17엔 7리만 제외
      expect(reg("4155040028", "2021-06-01")).toBe(false); // 12.18~ 죽산면 전체 제외
    });
    it("미양면 — 2020-09 지정(12.18 전) / 2021 제외", () => {
      expect(reg("4155034000", "2020-09-01")).toBe(true);
      expect(reg("4155034000", "2021-06-01")).toBe(false);
    });
    it("공도읍 — 제외 목록에 없어 지정 유지(2021)", () => {
      expect(reg("4155025000", "2021-06-01")).toBe(true);
    });
  });

  describe("용인 원삼면 — 6개 리만 제외", () => {
    it("사암리 제외 / 원삼면 비제외 리 지정 (2021)", () => {
      expect(reg("4146134022", "2021-06-01")).toBe(false); // 사암리(제외)
      expect(reg("4146134021", "2021-06-01")).toBe(true); // 원삼면 다른 리(예시·지정)
    });
  });

  describe("취득일/양도일 시점차 — 같은 주택", () => {
    it("김포 동지역: 취득(2021) 조정 / 양도(2023) 비조정", () => {
      expect(reg("4157010100", "2021-06-01")).toBe(true);
      expect(reg("4157010100", "2023-06-01")).toBe(false);
    });
  });
});
