/**
 * 지방 조정대상지역 anchor (P-A) — 광역시·세종·비수도권 시.
 *
 * 교재 변천표(2017.8.3~2025.10.16) + 국토부 고시 주석(주3·4·8·9) 고정.
 * 법정동코드는 행안부 표준. "동지역만" 시군구는 읍면 제외(high) 정밀 판정.
 */

import { describe, it, expect } from "vitest";
import { isRegulatedByBjdCode } from "@/lib/tax-engine/data/regulated-areas";

const reg = (code: string, date: string) => isRegulatedByBjdCode(code, date).isRegulated;
const conf = (code: string, date: string) => isRegulatedByBjdCode(code, date).confidence;

describe("지방 조정대상지역 anchor", () => {
  describe("부산 — 구별 시점 상이", () => {
    it("해운대구 — 2018 지정 / 2020-01 공백 미지정 / 2021 재지정 / 2023 미지정", () => {
      expect(reg("26350", "2018-06-01")).toBe(true);
      expect(reg("26350", "2020-01-01")).toBe(false); // 2019.11.8~2020.11.19 공백
      expect(reg("26350", "2021-06-01")).toBe(true);
      expect(reg("26350", "2023-06-01")).toBe(false);
    });
    it("연제구 — 2018-06 지정 / 2019-06 미지정(2018.12.31 해제·주4) / 2021 재지정", () => {
      expect(reg("26470", "2018-06-01")).toBe(true);
      expect(reg("26470", "2019-06-01")).toBe(false);
      expect(reg("26470", "2021-06-01")).toBe(true);
    });
    it("부산진구 — 2020.11.20 5개구엔 미포함 / 2020.12.18~ 지정", () => {
      expect(reg("26230", "2020-11-25")).toBe(false);
      expect(reg("26230", "2021-01-01")).toBe(true);
    });
    it("기장군 — 일광면 2018-10 지정(주3) / 기장읍 같은시점 미지정 / 일광 2019 해제 / 전역 2017-09", () => {
      expect(reg("2671031000", "2018-10-01")).toBe(true);  // 일광면 (8.28~12.30 일광만)
      expect(reg("2671025000", "2018-10-01")).toBe(false); // 기장읍 — 일광만 지정
      expect(reg("2671031000", "2019-06-01")).toBe(false); // 2018.12.31 해제(주4)
      expect(reg("2671025000", "2017-09-01")).toBe(true);  // 전역기간(8.3~8.27)
    });
    it("중구 — 전 기간 미지정 / 서구 — 2020.12.18 전 미지정·후 지정", () => {
      expect(reg("26110", "2021-06-01")).toBe(false);
      expect(reg("26140", "2020-11-25")).toBe(false);
      expect(reg("26140", "2021-01-01")).toBe(true);
    });
  });

  describe("대구 — 수성 vs 달성 읍면 제외", () => {
    it("수성구 — 2021 지정 / 2022-08 유지(2022.7.5 이후 수성만)", () => {
      expect(reg("27260", "2021-06-01")).toBe(true);
      expect(reg("27260", "2022-08-01")).toBe(true);
    });
    it("중구 — 2021 지정 / 2022-08 미지정(2022.7.5 수성만)", () => {
      expect(reg("27110", "2021-06-01")).toBe(true);
      expect(reg("27110", "2022-08-01")).toBe(false);
    });
    it("달성군 — 화원읍 지정 / 가창면 제외(주9)", () => {
      expect(reg("2771025000", "2021-06-01")).toBe(true);  // 화원읍 (지정)
      expect(reg("2771031000", "2021-06-01")).toBe(false); // 가창면 (제외)
    });
  });

  describe("대전·광주·울산", () => {
    it("대전 동구 — 2020.6.19 지정 / 2020-01 미지정 / 2023 미지정", () => {
      expect(reg("30110", "2020-07-01")).toBe(true);
      expect(reg("30110", "2020-01-01")).toBe(false);
      expect(reg("30110", "2023-06-01")).toBe(false);
    });
    it("광주 동구 — 2020.12.18 지정 / 2020-08 미지정", () => {
      expect(reg("29110", "2021-06-01")).toBe(true);
      expect(reg("29110", "2020-08-01")).toBe(false);
    });
    it("울산 중구 지정 / 동구 미지정", () => {
      expect(reg("31110", "2021-06-01")).toBe(true);
      expect(reg("31170", "2021-06-01")).toBe(false);
    });
  });

  describe("세종 — 동지역만 지정(행복도시 예정지역·주5)", () => {
    it("5자리(36110)만이면 medium(10자리 확인 필요) / 2023 해제", () => {
      expect(reg("36110", "2018-06-01")).toBe(true);
      expect(conf("36110", "2018-06-01")).toBe("medium");
      expect(reg("36110", "2023-06-01")).toBe(false);
    });
    it("동지역(10자리) high 지정 — 반곡동(101)·용호동(123) 경계", () => {
      expect(reg("3611010100", "2018-06-01")).toBe(true);
      expect(conf("3611010100", "2018-06-01")).toBe("high");
      expect(reg("3611012300", "2018-06-01")).toBe(true);
      expect(conf("3611012300", "2018-06-01")).toBe("high");
    });
    it("읍·면(조치원읍 250) high 미지정 — 비예정지역", () => {
      expect(reg("3611025000", "2018-06-01")).toBe(false);
      expect(conf("3611025000", "2018-06-01")).toBe("high");
    });
    it("동지역도 2022.11.13 해제 후 미지정", () => {
      expect(reg("3611010100", "2023-06-01")).toBe(false);
    });
  });

  describe("비수도권 시 — 동지역 지정 / 읍면 제외(high)", () => {
    it("청주 — 영동(동) 지정 / 낭성면 제외 / 오창읍 지정 / 내수읍 제외", () => {
      expect(reg("4311110100", "2021-06-01")).toBe(true);  // 동지역
      expect(reg("4311131000", "2021-06-01")).toBe(false); // 낭성면 제외
      expect(reg("4311425300", "2021-06-01")).toBe(true);  // 오창읍 (지정 유지)
      expect(reg("4311425000", "2021-06-01")).toBe(false); // 내수읍 제외
    });
    it("청주 — 2020.6.19 지정(수도권보다 이름)", () => {
      expect(reg("4311110100", "2020-07-01")).toBe(true);
    });
    it("천안 동남 대흥동 지정 / 목천읍 제외", () => {
      expect(reg("4413110100", "2021-06-01")).toBe(true);
      expect(reg("4413125000", "2021-06-01")).toBe(false);
    });
    it("포항 남구 상도동 지정 / 구룡포읍 제외", () => {
      expect(reg("4711110100", "2021-06-01")).toBe(true);
      expect(reg("4711125000", "2021-06-01")).toBe(false);
    });
    it("전주 완산 전동(읍면 없는 구) 지정", () => {
      expect(reg("4511111100", "2021-06-01")).toBe(true);
    });
    it("여수 소라면 지정(포함) / 돌산읍 제외", () => {
      expect(reg("4613031000", "2021-06-01")).toBe(true);  // 소라면 (포함)
      expect(reg("4613025000", "2021-06-01")).toBe(false); // 돌산읍 제외
    });
    it("순천 해룡면 지정(포함) / 승주읍 제외", () => {
      expect(reg("4615031000", "2021-06-01")).toBe(true);  // 해룡면
      expect(reg("4615025000", "2021-06-01")).toBe(false); // 승주읍
    });
    it("광양 광양읍 지정(포함) / 봉강면 제외", () => {
      expect(reg("4623025000", "2021-06-01")).toBe(true);  // 광양읍
      expect(reg("4623031000", "2021-06-01")).toBe(false); // 봉강면
    });
    it("경산 삼남동 — 2021 지정 / 2022-08 미지정(2022.7.5 해제)", () => {
      expect(reg("4729010100", "2021-06-01")).toBe(true);
      expect(reg("4729010100", "2022-08-01")).toBe(false);
    });
  });
});
