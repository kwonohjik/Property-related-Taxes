/**
 * `parseCitations` — 한 문자열에 담긴 여러 조문 인용 파싱
 *
 * ── 왜 필요했나 (2026-08-05) ────────────────────────────────────────────────
 * `parseCitation`은 **앞쪽 하나만** 읽는다. legal-codes에는 복합 인용이 흔한데
 * (`"소득세법 시행령 §168조의11 ② + 소득세법 시행규칙 §83조의4"`), 뒤쪽 조문이
 * 커버리지 모수에 아예 들어가지 못했다 — 실제로 이 파서를 넣자 **숨어 있던 10개
 * 조문**이 드러났다(소칙 §83의4·§83의5, 상증령 §32의4·§51·§58의2·§62 등).
 *
 * ⚠️ 법령명이 생략된 후속 세그먼트는 **직전 법령을 승계**한다. 이 추론은 같은 법령의
 *    연속 인용("소득세법 시행령 §167의10①4호·§155⑧")에서는 맞지만, 법령이 바뀌는
 *    자리에서는 틀린다 — 실제로 `"상증령 §52의2② (소법 §99①3·§63①1가목 준용)"`이
 *    상증법 §63을 소득세법 §63으로 오귀속시켰다(원문을 명시적으로 고쳐 해소).
 *    ⇒ 복합 인용을 새로 쓸 때는 **법령이 바뀌는 세그먼트에 법령명을 반드시 적을 것.**
 */
import { describe, it, expect } from "vitest";
import { parseCitations } from "@/lib/legal-verification/citation-parser";

const keys = (raw: string) =>
  parseCitations(raw).map((p) => `${p.lawFullName} ${p.articleNo}`);

describe("parseCitations — 복합 인용", () => {
  it("단일 인용은 1건 그대로", () => {
    expect(keys("소득세법 §95 ②")).toEqual(["소득세법 제95조"]);
  });

  it("`+` 구분 — 법령이 바뀌는 복합 인용", () => {
    expect(keys("소득세법 시행령 §168조의11 ② + 소득세법 시행규칙 §83조의4")).toEqual([
      "소득세법 시행령 제168조의11",
      "소득세법 시행규칙 제83조의4",
    ]);
  });

  it("`·` 구분 — 3개 법령", () => {
    expect(keys("상증법 §61③·상증령 §51·상증규 §16")).toEqual([
      "상속세 및 증여세법 제61조",
      "상속세 및 증여세법 시행령 제51조",
      "상속세 및 증여세법 시행규칙 제16조",
    ]);
  });

  it("괄호 그룹도 독립 세그먼트로 파싱", () => {
    expect(keys("소득세법 시행령 §168조의14 ① (소득세법 시행규칙 §83의5①)")).toEqual([
      "소득세법 시행령 제168조의14",
      "소득세법 시행규칙 제83조의5",
    ]);
  });

  it("법령명이 생략된 후속 세그먼트는 직전 법령을 승계", () => {
    expect(keys("소득세법 시행령 §167의10①4호·§155⑧")).toEqual([
      "소득세법 시행령 제167조의10",
      "소득세법 시행령 제155조",
    ]);
  });

  it("설명 꼬리는 조·항 표기가 없어 걸러진다", () => {
    expect(keys("상속세 및 증여세법 시행령 §50 ⑦ — 임대료 등의 환산가액 (12%, 2009.4.23. 시행)")).toEqual([
      "상속세 및 증여세법 시행령 제50조",
    ]);
  });

  it("같은 조를 두 번 가리키면 중복 제거", () => {
    expect(keys("소득세법 §104 ① · 소득세법 §104 ⑦")).toEqual(["소득세법 제104조"]);
  });

  it("인용이 아닌 문자열은 빈 배열", () => {
    expect(keys("미등기 양도자산 — 장기보유특별공제 배제")).toEqual([]);
  });
});
