/**
 * 문서번호 비교 키 — 출처마다 다른 실표기(카드·taxlaw 상세·DRF 검색·DRF 조세심판)를 같은 키로 모은다.
 * 표기는 모두 2026-10-21 실응답·카드에서 옮겼다.
 */
import { describe, it, expect } from "vitest";
import { docDate, docKey } from "@/lib/korean-law/doc-key";

describe("docKey — 같은 문서의 다른 표기", () => {
  const same: [string, string][] = [
    // 카드 [꼬리] ↔ taxlaw 상세
    ["서면-2016-법령해석재산-3189 [법령해석과-2507]", "서면-2016-법령해석재산-3189"],
    // DRF 해석 검색은 꼬리를 붙여 쓴다
    ["사전-2025-법규재산-0190[법규과-1109]", "사전-2025-법규재산-0190"],
    // 기재부: 카드·taxlaw는 「기획재정부 」 접두사 + 꼬리 안에 괄호·날짜 ↔ DRF는 접두사 없음
    ["기획재정부 조세정책과-1199 [조세정책과-1199(2024.6.25.)]", "조세정책과-1199"],
    ["재산세제과-906[재산세제과-906(2024.07.31.)]", "기획재정부 재산세제과-906"],
    ["재정경제부 재산세제과-123", "재산세제과-123"],
    // 조세심판: DRF 「조심 2025중4302」 ↔ 카드 「조심-2025-중-4302」
    ["조심 2025중4302", "조심-2025-중-4302"],
  ];
  it.each(same)("%s ≡ %s", (a, b) => expect(docKey(a)).toBe(docKey(b)));

  const unchanged: [string, string][] = [
    ["서면인터넷방문상담4팀-977", "서면인터넷방문상담4팀977"],
    ["재일46014-1748", "재일460141748"],
    ["심사양도2002-0086", "심사양도20020086"],
    ["대법원-2007-두-8973", "대법원2007두8973"],
  ];
  it.each(unchanged)("%s → %s", (a, b) => expect(docKey(a)).toBe(b));

  it("번호가 다르면 키도 다르다 — 부분 일치를 같다고 보지 않는다", () => {
    expect(docKey("조세정책과-69")).not.toBe(docKey("조세정책과-695"));
  });
});

describe("docDate — 「YYYY.MM.DD.」", () => {
  it.each([
    ["2026.06.08", "2026.06.08."],
    ["2016.03.31.", "2016.03.31."],
    ["20160331", "2016.03.31."],
  ])("%s → %s", (a, b) => expect(docDate(a)).toBe(b));
  it("해석할 수 없으면 null", () => {
    expect(docDate("")).toBeNull();
    expect(docDate(undefined)).toBeNull();
    expect(docDate("2016-3-31")).toBeNull();
  });
});
