/**
 * 소스 정적 가드용 — **주석을 지운 소스**.
 *
 * ## 왜 공용인가 — 같은 함정을 두 번 밟았다
 *
 * 「이 파일이 X를 쓰지 않는다」를 원문 그대로 세면 **설명하는 주석이 증거로 잡힌다**:
 *
 *   · P5-b-1 `one-house-provenance-four-views.guard`: 단건 결과뷰의 JSDoc에 있던
 *     `<PrintSection id="...">` 문자열이 「열림 1 · 닫힘 0」을 만들어 가드가 빨개졌다.
 *   · P5-b-2 `one-house-judgment-load-modal`: 「`updateFormData`를 여기서 부르면 안 된다」는
 *     **금지를 설명하는 주석**이 곧 그 금지의 위반 증거로 잡혀 4건이 빨개졌다.
 *
 * 두 번째가 났을 때 사본을 하나 더 만들지 않고 여기로 올렸다. 정적 가드를 새로 쓸 때는
 * **먼저 이것을 통과시킨 소스**에 대고 단언할 것.
 *
 * ⚠️ 정규식 기반이라 문자열 리터럴 안의 `//`·`/*`까지는 구분하지 못한다. URL을 오인하지
 *    않도록 `//` 앞 한 글자를 보존한다(`https://`가 주석으로 먹히는 것을 막는다).
 */
export function stripComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/[^\n]*/g, "$1");
}
