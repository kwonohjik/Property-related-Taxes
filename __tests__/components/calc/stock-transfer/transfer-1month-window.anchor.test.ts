/**
 * A-6~A-9 anchor — 「양도일 이전 1개월」 기준시가 윈도우
 *
 * 근거 (KoreanLaw MCP 실측):
 *   소득세법 §99①3 — 「상속세 및 증여세법」 §63①1가목을 준용하되
 *     "평가기준일 이전ㆍ이후 각 2개월" → "**양도일ㆍ취득일 이전 1개월**"
 *   상증법 §63①1가목 — 평가기준일(**매매가 없는 날이면 그 전일을 기준으로 한다**) 이전ㆍ이후 각 2개월
 *   상증령 §52의2④ — 「매매가 없는 날」 = 공휴일·대체공휴일·토요일
 *
 * ⇒ 축은 **양도일 당일**이고 「이전」은 당일을 포함해 소급한다.
 *   비거래일 양도이면 **직전 거래일**로 기준을 옮긴다(윈도우 전체가 함께 이동).
 *
 * 안전망 실측(P-4): 시작일을 +7일 옮겨도 반응하는 테스트가 **0건**이었다.
 * 이 anchor가 유일한 방어선이다.
 *
 * 계획서: docs/00-pm/stock-transfer-stale-result-and-conversion-display.plan.md §3-3
 */

import { describe, it, expect } from "vitest";
import {
  preTransferAutoFillDates,
  resolvePreTransferAnchor,
} from "@/components/calc/stock-transfer/PostListingClosingPriceTable";

const first = (d: string) => preTransferAutoFillDates(d)[0];
const last = (d: string) => {
  const a = preTransferAutoFillDates(d);
  return a[a.length - 1];
};

describe("A-8 (대조군) — 거래일 평일 양도일은 당일을 포함한다", () => {
  it("A-8-1: 2023-02-24(금) → [2023-01-25 ~ 2023-02-24]", () => {
    expect(resolvePreTransferAnchor("2023-02-24")).toBe("2023-02-24");
    expect(first("2023-02-24")).toBe("2023-01-25");
    expect(last("2023-02-24")).toBe("2023-02-24");
  });

  it("A-8-2: 2024-06-03(월) → [2024-05-04 ~ 2024-06-03]", () => {
    expect(last("2024-06-03")).toBe("2024-06-03");
    expect(first("2024-06-03")).toBe("2024-05-04");
  });

  it("A-8-3: 주말 양도일은 §63①1가목 괄호대로 직전 거래일 기준 — 2024-06-01(토) → 2024-05-31", () => {
    expect(resolvePreTransferAnchor("2024-06-01")).toBe("2024-05-31");
    expect(last("2024-06-01")).toBe("2024-05-31");
  });
});

describe("A-6 — 월말 양도일에서 윈도우가 잘리지 않는다", () => {
  /**
   * 결함: 시작일을 `(월 − 1, 일 + 1)`로 기계 계산해 2월이 짧으면 오버플로가 났다.
   *   2023-03-31 → (2023, 2월, 32일) → **2023-03-04** (28일치만 남음)
   * 민법 §160②: 월로 정한 기간은 역에 의해 계산하고, 해당일이 없으면 그 월의 말일로 만료한다.
   *   ⇒ 2023-03-31의 소급 1개월은 2023-02-28 ⇒ 윈도우 시작은 그 다음날 2023-03-01
   */
  it("A-6-1: 2023-03-31(금·평년) → 시작 2023-03-01 (현행 결함: 03-04)", () => {
    expect(first("2023-03-31")).toBe("2023-03-01");
    expect(last("2023-03-31")).toBe("2023-03-31");
  });

  it("A-6-2: 2023-05-31(수) → 시작 2023-05-01 (4월은 30일 · 현행 결함: 05-02)", () => {
    // 소급 1개월 = 2023-04-30 ⇒ 시작은 그 다음날 05-01
    expect(first("2023-05-31")).toBe("2023-05-01");
    expect(last("2023-05-31")).toBe("2023-05-31");
  });

  it("A-6-3 (대조군): 오버플로가 없는 달은 종전과 같다 — 2023-01-31(화) → 시작 2023-01-01", () => {
    // 12월은 31일이라 소급이 정확히 2022-12-31 ⇒ 시작 2023-01-01
    expect(first("2023-01-31")).toBe("2023-01-01");
    expect(last("2023-01-31")).toBe("2023-01-31");
  });

  it("A-6-4 (대조군): 윤년 2월은 이미 정상 — 2024-03-29(금) → 시작 2024-03-01", () => {
    // 2024-02-29가 실재하므로 소급이 그 날로 떨어진다 ⇒ 시작 03-01
    expect(first("2024-03-29")).toBe("2024-03-01");
    expect(last("2024-03-29")).toBe("2024-03-29");
  });
});

// ✅ Q-4 결정(2026-08-27): 「주말만」 → 「공휴일·납회 포함」으로 확대.
//    근거는 상증법 §63①1가목 괄호(「매매가 없는 날이면 **그 전일**을 기준」) + 상증령 §52의2④.
//    같은 조문에서 나온 상증세 평가용 `resolveValuationAnchor`가 이미 그렇게 동작하고 있어
//    두 세목이 갈려 있던 것을 합쳤다. `__tests__/kiwoom/calendar.test.ts`의 종전 기대값도 함께 갱신.
describe("A-7 — 평일 공휴일·납회기간 양도일도 직전 거래일로 옮긴다", () => {
  /**
   * 상증령 §52의2④의 「매매가 없는 날」은 공휴일·대체공휴일·토요일이다.
   * 현행 `resolvePreTransferAnchor`는 **토·일만** 보므로 평일 공휴일에서 시프트가 일어나지 않는다.
   */
  it("A-7-1: 2024-03-01(금·삼일절) → anchor 2024-02-29", () => {
    expect(resolvePreTransferAnchor("2024-03-01")).toBe("2024-02-29");
  });

  it("A-7-2: 2023-12-29(금·납회) → anchor 2023-12-28", () => {
    expect(resolvePreTransferAnchor("2023-12-29")).toBe("2023-12-28");
  });

  it("A-7-3: 시프트된 anchor 기준으로 윈도우 끝이 이동한다", () => {
    expect(last("2024-03-01")).toBe("2024-02-29");
  });
});

describe("A-9 — 휴장일 픽스처 범위 밖은 시프트하지 않는다", () => {
  /**
   * `isKrxHolidayInFixture`는 KRX_HOLIDAYS_2020_2026 정적 Set 조회다.
   * 범위 밖 연도는 휴장일을 알 수 없으므로 **모르는 것을 아는 척하지 않는다** —
   * 주말만 보정하고 평일은 그대로 둔다. (화면에서 별도 안내를 띄운다.)
   */
  it("A-9-1: 2018-03-01(목·삼일절이지만 픽스처 밖) → 시프트 없음", () => {
    expect(resolvePreTransferAnchor("2018-03-01")).toBe("2018-03-01");
  });

  it("A-9-2: 범위 밖이어도 주말은 보정한다 — 2018-03-03(토) → 2018-03-02", () => {
    expect(resolvePreTransferAnchor("2018-03-03")).toBe("2018-03-02");
  });
});
