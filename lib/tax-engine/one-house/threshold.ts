/**
 * 1세대1주택 「고가주택」 기준금액 — **양도일** 기준 시점 함수 (G-5).
 *
 * 계획서: `docs/00-pm/one-house-exemption-automation.plan.md` §4 G-5 · §9 P1.
 * 엔진 설계: `docs/02-design/features/one-house-exemption-automation.engine.design.md` 「계산 알고리즘」 1.
 *
 * 종전에는 판정도 안분도 **12억 단일값**이었다(세율 seed `maxExemptPrice` · 호출부 하드코딩 6곳).
 * 그래서 과거 양도분이 **전액 비과세**로 계산됐다 — 2021-12-07 10억 양도(취득 5억)가 0원,
 * 2008-10-06 7억 양도(취득 3억)가 0원.
 *
 * ## 연혁 (법제처 DRF `target=eflaw` 실독, 2026-09-20 재확인)
 *
 * | 양도일 | 기준 | 근거 |
 * |---|---|---|
 * | ~ 2008-10-06 | **6억원** 초과 | 소득세법 시행령 §156① (구 규정) |
 * | 2008-10-07 ~ 2021-12-07 | **9억원** 초과 | 소득세법 시행령 §156① (대통령령 제21062호) |
 * | 2021-12-08 ~ | **12억원** 초과 | 소득세법 §89①3호 괄호 (법률 제18578호) |
 *
 * **두 경계 모두 기준은 「양도일」이다.**
 * - 12억: 법률 제18578호 부칙 제1조3호(시행 = 공포한 날 **2021-12-08**) + 제7조④
 *   「시행일 이후 **양도하는 주택부터** 적용한다」. 실측 MST 237497 — 공포·시행 모두 2021-12-08.
 * - 9억: 대통령령 제21062호 부칙 제1조(공포한 날 시행) + 제2조 「시행 후 최초로 **양도하는 분부터**」.
 *   실측 MST 89130 — 공포·시행 모두 **2008-10-07**. 직전 시행본은 2008-09-22(제21025호)이고
 *   **2008-10-06에 시행된 개정은 없다** ⇒ 6억은 2008-10-06까지.
 *
 * 🔑 **위임 체인이 바뀌었다.** 2021-12-07까지 법률에는 금액이 없고 「대통령령으로 정하는 기준」이라는
 *    위임 문언만 있었다 — 9억은 **시행령**에 있었다. 법률만 보면 놓친다.
 *
 * ⚠️ **2005-02-19 이전은 미확인**이다(DRF 시행일 목록 범위 밖). 그 구간도 6억을 돌려주지만
 *    근거를 확보한 값이 아니다 — 계획서 V-6 잔여 항목.
 *
 * ⚠️ **이 함수는 「주택」 축이다.** 조합원입주권(§89①4호 단서)은 2021-12-07까지 금액이 법률에
 *    없고 시행령에 위임돼 있었는데, **그 위임 조항의 번호와 연혁을 아직 실독하지 않았다**.
 *    근거를 확보하지 못한 채 더 낮은 기준을 소급하면 납세자에게 불리한 방향으로 틀린다 ⇒
 *    입주권 경로(`applyOneRightExemption`)는 이 함수를 쓰지 않는다. 계획서 P3에서 다룬다.
 */

/** 소득세법 시행령 §156① 9억 개정 시행일 — 대통령령 제21062호(공포·시행 2008-10-07). */
export const HIGH_VALUE_HOUSE_9EOK_EFFECTIVE_DATE = new Date("2008-10-07");

/** 소득세법 §89①3호 괄호 12억 시행일 — 법률 제18578호(공포·시행 2021-12-08). */
export const HIGH_VALUE_HOUSE_12EOK_EFFECTIVE_DATE = new Date("2021-12-08");

const THRESHOLD_6EOK = 600_000_000;
const THRESHOLD_9EOK = 900_000_000;
const THRESHOLD_12EOK = 1_200_000_000;

/**
 * 양도일에 시행 중이던 1세대1주택 고가주택 기준금액(원)을 돌려준다.
 *
 * 「초과」 기준이다 — 반환값 **이하**면 고가주택이 아니다.
 *
 * @param transferDate 양도일. **자산별 양도일**을 넘길 것 —
 *   다건 route는 과세기간 말일로 세율 행을 고르므로(`app/api/calc/transfer/multi/route.ts`)
 *   규칙 행에서 기준금액을 읽으면 2021년 11월 양도가 12억 행을 받는다.
 *   그래서 이 값은 규칙 행이 아니라 이 함수가 단일 소스로 정한다.
 */
export function resolveHighValueHouseThreshold(transferDate: Date): number {
  // Date가 아닌 값(JSON 경유 string 등)이 오면 조용히 6억으로 떨어지지 않도록 즉시 실패시킨다.
  // `Date < string`은 silent false라 납세자에게 불리한 방향으로 조용히 틀린다.
  const t = transferDate.getTime();
  if (t >= HIGH_VALUE_HOUSE_12EOK_EFFECTIVE_DATE.getTime()) return THRESHOLD_12EOK;
  if (t >= HIGH_VALUE_HOUSE_9EOK_EFFECTIVE_DATE.getTime()) return THRESHOLD_9EOK;
  return THRESHOLD_6EOK;
}

/**
 * 기준금액의 **표시 문구** — 「12억」처럼 억 단위로 읽는다.
 *
 * 세 값(6억·9억·12억)이 전부 억 단위 정수라 나눗셈이 떨어진다.
 * 화면·산출근거 문구가 「12억」을 리터럴로 적으면 과거 양도분에서 **적힌 값과 실제 기준이
 * 어긋난다** — 산식이 자기 값을 만들지 못하게 된다.
 */
export function formatHighValueThresholdLabel(threshold: number): string {
  return `${threshold / 100_000_000}억`;
}
