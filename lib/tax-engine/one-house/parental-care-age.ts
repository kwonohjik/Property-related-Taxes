/**
 * 동거봉양 합가(「소득세법 시행령」 §155④ · §156의2⑧2호 · §155② 단서)의 **직계존속 연령 요건** 단일 소스 — 결정 #9 (리뷰 G6-2).
 *
 * 조문(KoreanLaw MCP — 현행 MST 290841 원문):
 *   · §155④ 본문 「1주택을 보유하고 있는 60세 이상의 직계존속(다음 각 호의 사람을 포함하며 …)을 동거봉양하기 위하여 세대를 합침으로써」 —
 *     1호 배우자의 직계존속으로서 60세 이상인 사람 · 2호 직계존속(배우자의 직계존속 포함) 중 어느 한 사람이 60세 미만인 경우 ·
 *     3호 요양급여를 받는 60세 미만의 직계존속으로서 재정경제부령으로 정하는 사람.
 *   · §156의2⑧2호 — 60세 요건은 있으나 **요양급여 예외가 없다**.
 *   · §155② 단서 「세대를 합친 날 현재 직계존속 중 어느 한 사람 또는 모두가 60세 이상으로서 1주택을 보유하고 있는 경우만 해당」 —
 *     역시 요양급여 예외가 없다.
 * 연령 기준일은 **합가일 현재 만 나이**이고 60세 이상인 사람은 주택 보유자가 아니어도 된다(재산세과-291 · 서면법규과-820 ·
 * 사전-2015-법령해석재산-0424). 2009.2.3. 이전 합가분의 여자 55세 기준은 엔진에서 판정하지 않고 안내 문구로만 알린다
 * (오래된 연혁은 범위 밖 — 2026-10-09 혼인합가 2012.2.2. 전 연혁과 같은 방향).
 *
 * 이 leaf가 합가 의제의 모든 소비처(비과세 E-3.5 · 중과 배제 ① 요소 · §155⑳ 합가 중첩 · 이중 합가 · §89② 입주권·분양권 ⑧ ·
 * 양론 C6)에 같은 판정을 준다 — 손술어 사본 금지.
 */
import type { ParentalCareParentAge } from "../types/transfer.types";

export type { ParentalCareParentAge };

/** `met` = 연령 요건 충족 · `unmet` = 해당하지 않는다고 선언(사실) · `unknown` = 미선택(모름 → 불성립 + 확인 필요). */
export type ParentalCareAgeVerdict = "met" | "unmet" | "unknown";

/**
 * @param path `"155_4"` = §155④ 경로(요양급여 갈래 인정) / `"156_2_8"` = §156의2⑧2호·§155② 단서 경로(60세 이상만).
 */
export function parentalCareAgeVerdict(
  parentAge: ParentalCareParentAge | undefined,
  path: "155_4" | "156_2_8",
): ParentalCareAgeVerdict {
  if (parentAge === undefined) return "unknown";
  if (parentAge === "over_60") return "met";
  if (parentAge === "care_benefit") return path === "155_4" ? "met" : "unmet";
  return "unmet";
}

