/**
 * 소유자 분리(토지만 본인 소유) 주택 카드의 §99·§99의3 적용 배제 사유 (리뷰 NH-08 · Q-28).
 *
 * 조특법 §99의3① · §99①은 «신축주택(그 주택에 딸린 토지 포함)을 취득하여 양도»한 거주자를 감면 대상으로 한다.
 * 주택과 부수토지의 소유자가 다르면 소유자들이 같은 세대원이어도 부수토지의 양도소득은 신축주택 감면 대상에
 * 포함되지 않는다 — 서면인터넷방문상담4팀-1118(2005.07.01.) · 국심2006중4504(2007.06.07.) · 조심2013중3556(2013.12.04.).
 * 세 건 모두 §99의3 사건이다. §99는 문언 구조가 같지만 정면 해석례가 없어 §99의3 해석을 따르되 «확인 필요»를 고지한다(Q-28).
 *
 * 평가기(`evaluateNew993`·`evaluateNew99`)가 입력 `isLandOnlyOwner`를 받아 이 사유를 **가장 먼저** 낸다 —
 * 라우터가 STEP 4.6(소득금액 차감)과 STEP 0.45(중과 배제 선판정)에 같은 값을 넘기므로 «감면은 안 되는데 중과만 배제»되는 어긋남이 없다.
 */
export const LAND_ONLY_OWNER_CODE = "LAND_ONLY_OWNER";

const RULINGS = "서면인터넷방문상담4팀-1118 · 국심2006중4504 · 조심2013중3556";

export function landOnlyOwnerMessage(article: "new_99_3" | "new_99"): string {
  if (article === "new_99_3") {
    return (
      "토지만 본인 소유이고 신축주택(건물)은 다른 사람 소유라, 이 토지의 양도소득은 §99의3 신축주택 과세특례 대상이 아닙니다 — " +
      `주택과 부수토지의 소유자가 다르면 같은 세대원이어도 부수토지의 양도소득은 신축주택 감면 대상에 포함되지 않습니다 (${RULINGS}).`
    );
  }
  return (
    "토지만 본인 소유이고 신축주택(건물)은 다른 사람 소유라, 이 토지의 양도소득은 §99 신축주택 감면 대상이 아닌 것으로 처리했습니다 — " +
    `§99에 대한 정면 해석례는 없고, 같은 문언 구조(신축주택과 그 딸린 토지를 취득하여 양도)의 §99의3 해석을 따랐습니다 (${RULINGS}). ` +
    "확인 필요: §99에도 같은 해석이 적용되는지 관할 세무서에 확인하세요."
  );
}
