/** 괄호 「2020년 7월 11일 이후 … 등록 신청한」 */
export const APT_PURCHASE_973_FROM = "2020-07-11";
/** 매입임대 등록 시한(종전 ① 「2020년 12월 31일」) — 이 날 뒤 등록분은 시한 사유가 막는다 */
export const APT_PURCHASE_973_TO = "2020-12-31";

/**
 * 질문 표시·필수 여부 — 장기 등록일(변경신고 주택은 수리일)이 질문 구간 안이고 변경신고 주택이 아닐 때.
 * 날짜는 `YYYY-MM-DD` 문자열 또는 UTC 자정 Date(엔진).
 */
export function aptPurchase973QuestionApplies(a: {
  longRegistrationDate?: Date | string;
  isShortTermConversion: boolean;
}): boolean {
  if (a.isShortTermConversion) return false;
  const reg = iso(a.longRegistrationDate);
  return reg !== undefined && reg >= APT_PURCHASE_973_FROM && reg <= APT_PURCHASE_973_TO;
}

function iso(d: Date | string | undefined): string | undefined {
  if (d === undefined || d === "") return undefined;
  if (typeof d === "string") return d.slice(0, 10);
  return Number.isNaN(d.getTime()) ? undefined : d.toISOString().slice(0, 10);
}

