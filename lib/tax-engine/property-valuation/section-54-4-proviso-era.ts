/**
 * 상증령 §54④ 단서(3·5호) 연혁 게이트 — U-03 (비상장주식 리뷰 2026-11-28).
 *
 * - 현행 §54④ 단서: 「다만, 제3호 및 제5호의 경우에는 제1항 본문에 따라 평가한 가액이 1주당 순자산가치보다
 *   낮은 경우로 한정한다」 — 대통령령 제36131호(2026.2.27.)로 신설. 그 전 시행본(2025.10.01. 등)에는 단서가 없어
 *   3·5호에 해당하면 무조건 순자산가치로 평가했다.
 * - 부칙 <제36131호> 제11조: 「제54조제4항의 개정규정은 이 영 시행 이후 평가하는 경우부터 적용한다.」
 * - 「평가하는 경우」 = 평가기준일이 도래하는 경우 — 같은 문구의 부칙 <제28638호> 제8조에 대한
 *   기획재정부 재산세제과-955(2021.11.02.) 회신(서면-2019-법령해석재산-1035 인용, 원문 확인 2026-11-28).
 */

/** §54④ 단서 시행일 (UTC 자정) — 평가기준일이 이 날 이후면 단서 적용 */
export const SECTION_54_4_PROVISO_FROM = new Date(Date.UTC(2026, 1, 27));

/**
 * 평가기준일에 §54④ 단서(3·5호 «가중평균 < 순자산일 때만»)가 적용되는지.
 * 날짜를 모르면(간편평가 미리보기 등) 현행 본문(단서 적용)으로 본다 — 종전 동작 유지.
 */
export function hasSection54_4Proviso(evaluationDate: Date | undefined): boolean {
  if (!evaluationDate || isNaN(evaluationDate.getTime())) return true;
  return evaluationDate.getTime() >= SECTION_54_4_PROVISO_FROM.getTime();
}
