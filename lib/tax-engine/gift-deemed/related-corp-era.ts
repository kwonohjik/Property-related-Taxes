/**
 * §45의3 일감몰아주기 — **행위시법(증여시기별 적용 법령) 축**.
 *
 * §45의3③은 「증여의제이익의 계산은 수혜법인의 **사업연도 단위**로 하고, 수혜법인의 해당
 * **사업연도 종료일을 증여시기**로 본다」고 증여시기를 명문으로 고정한다. 그 날에 시행 중이던
 * 법령이 적용되므로, 사업연도 종료일에 따라 계산식 자체가 갈린다.
 *
 * ── 확정된 시점 지도 (KoreanLaw MCP 원문 실측) ──────────────────────
 *
 * **~2017-12-31 (법률 제14839호, 시행 2017-07-26)** — §45의3① verbatim:
 *   「수혜법인의 세후 영업이익 × 정상거래비율의 1/2[수혜법인이 중소기업 … 또는 대통령령으로
 *     정하는 중견기업에 해당하는 경우에는 정상거래비율]을 초과하는 특수관계법인거래비율 ×
 *     한계보유비율을 초과하는 주식보유비율」
 *   ⇒ **단일 계산식**이고 과세요건도 「정상거래비율 초과」 하나뿐이다.
 *
 * **2018-01-01~ (법률 제15224호, 2017-12-19 공포)** — §45의3①이 1호(과세요건)·2호(이익)로
 *   갈리고, 2호가 **가목(중소)·나목(중견)·다목(일반)** 3분기가 된다. 이 엔진의
 *   `TRADE_RATIO_DEDUCTION`·`OWNERSHIP_RATIO_DEDUCTION`은 그 3분기를 그대로 구현한 것이다
 *   (2018-01-01 시행본 verbatim: 가목 「정상거래비율을 초과」 / 나목 「정상거래비율의 100분의
 *   50을 초과 … 한계보유비율의 100분의 50을 초과」 / 다목 「100분의 5를 초과 … 주식보유비율」).
 *
 * ⇒ 구법 구간은 **계산하지 않고 차단**한다. 「현행 산식으로 조용히 계산」은 선택지가 아니다:
 *   - 구법의 중견기업은 정상거래비율이 중소와 같은 100분의 50이었다(구 영 §34의2⑤). 현행
 *     100분의 40으로 계산하면 **과세요건조차 미충족인 건에 세금이 생긴다**(실측 37,500,000원).
 *   - 일반기업도 차감비율이 달라 실측 27,500,000원 과대였다. 둘 다 납세자 **불리** 방향이다.
 *   - 구법을 제대로 구현하려면 그 시점의 영 §34의2 전부(정상거래비율·한계보유비율·세후영업이익의
 *     과세매출비율·과세제외매출)가 함께 필요한데, 그 축들의 시점은 **미확인**이다. 하나만
 *     구현하면 나머지가 현행으로 섞여 여전히 틀린다.
 *
 * ⚠️ **미확인으로 남은 것 — 법률 제15224호 부칙의 적용례 원문**.
 *   KoreanLaw MCP가 그 개정본 자신의 부칙을 노출하지 않는다(applicable_law는 기준일 **이후**
 *   부칙만 발췌하고, get_law_text는 `jo="부칙"`을 NOT_FOUND로 돌려준다).
 *   상증법의 통상형 일반적 적용례(「이 법 시행 이후 … 증여를 받는 경우부터 적용」)라면
 *   §45의3③상 증여시기 = 사업연도 종료일이므로 종료일 기준이 맞다. 그러나 「시행 후 **개시하는
 *   사업연도**부터」형이면 2018-01-01 전에 개시한 사업연도도 구법이다.
 *   ⇒ **확실한 구간만 차단**하고(종료일 < 2018-01-01), 걸칠 수 있는 구간에는 **고지**를 단다.
 *     추정으로 차단 범위를 넓히지 않는다.
 */

/** 법 §45의3① 계산식이 가·나·다목 3분기로 개편된 날 — 법률 제15224호. */
export const RC_TIERED_FORMULA_FROM = "2018-01-01";

/**
 * 이 앱이 계산할 수 없는 시점인지 판정한다. 반환값이 있으면 그것이 차단 사유다.
 * 사업연도 종료일 미전달이면 현행으로 본다(종전 동작 유지 — 무회귀 안전판).
 */
export function resolveRcEraExclusion(fiscalYearEndDate?: string): string | undefined {
  if (!fiscalYearEndDate) return undefined;
  const d = fiscalYearEndDate.slice(0, 10);
  if (d < RC_TIERED_FORMULA_FROM) {
    return (
      `사업연도 종료일 ${d}은 구 상증법 §45의3(법률 제14839호) 적용 대상입니다 — ` +
      "당시 계산식은 「세후영업이익 × 정상거래비율의 1/2(중소·중견은 정상거래비율)을 초과하는 " +
      "특수관계법인거래비율 × 한계보유비율을 초과하는 주식보유비율」 **하나**였고, 중견기업의 " +
      "정상거래비율도 중소기업과 같은 100분의 50이었습니다. 이 화면은 " +
      `${RC_TIERED_FORMULA_FROM} 시행(법률 제15224호) 이후의 가·나·다목 3분기 체계만 계산합니다.`
    );
  }
  return undefined;
}

/**
 * 계산은 하되 **확인이 필요한** 구간의 고지. 없으면 undefined.
 *
 * 고지는 «여지가 있을 때만» 뜬다 — 상시 고지는 노이즈가 되어 곧 무시된다.
 * 2018년에 종료하는 사업연도만 부칙 적용례에 따라 구법이 될 여지가 있다
 * (2019-01-01 이후 종료 사업연도는 어떤 적용례 형태로도 2018-01-01 이후 개시분이다).
 */
export function resolveRcEraNotice(fiscalYearEndDate?: string): string | undefined {
  if (!fiscalYearEndDate) return undefined;
  const d = fiscalYearEndDate.slice(0, 10);
  if (d >= RC_TIERED_FORMULA_FROM && d < "2019-01-01") {
    return (
      `사업연도 종료일이 ${d}입니다 — 이 사업연도가 ${RC_TIERED_FORMULA_FROM} **전에 개시**했다면 ` +
      "법률 제15224호 부칙의 적용례에 따라 구법(단일 계산식)이 적용될 수 있습니다. " +
      "이 화면은 개정법 기준으로 계산했습니다. 신고 전 부칙 적용례를 확인하세요."
    );
  }
  return undefined;
}
