/**
 * §45의5 특정법인 — **행위시법(증여시기별 적용 법령) 축**.
 *
 * §45의5①은 「**거래한 날**을 증여일로 하여」라고 증여시기를 명문으로 고정한다.
 * 그 날에 시행 중이던 법령이 적용되므로, 거래일에 따라 산식과 적용 여부가 갈린다.
 * 종전에는 이 축이 없어 1996년 거래든 2035년 거래든 **현행 산식으로 조용히 계산**됐다.
 *
 * ── 확정된 시점 지도 (전건 KoreanLaw MCP 원문 확인) ───────────────────
 *
 * | 거래일(증여일)        | 법 §45의5                    | 영 §34의5⑨ 증여세 상당액 base |
 * |---------------------|------------------------------|---------------------------|
 * | ~ 2019-12-31        | 구 체계 · **②에 한도 없음**    | (⑨ 자체가 없다)             |
 * | 2020-01-01~02-10    | 현행 ①② 시행                  | 위임 시행령 **미시행**       |
 * | 2020-02-11~2022-02-14 | 현행 ①②                    | **net** (증여의제이익)       |
 * | 2022-02-15 ~        | 현행 ①②                      | **gross** (④1호 × 보유비율)  |
 *
 * ① **구 체계(~2019-12-31)** — 법률 제16102호(시행 2019.1.1) §45의5 verbatim:
 *    ①은 「1. 결손금이 있는 법인 / 2. 휴업 또는 폐업 상태인 법인 / 3. … 지배주주와 그 친족의
 *    주식보유비율이 **100분의 50 이상**인 법인」의 3분류이고, ②는 「제1항에 따른 **거래는** 다음
 *    각 호의 어느 하나에 해당하는 것으로 한다」 — 즉 **거래 유형** 조항이지 한도 조항이 아니다.
 *    한도(②)는 법률 제16846호(시행 2020.1.1)에서 **신설**됐다(같은 항 번호, 완전히 다른 내용).
 *    ⇒ 이 앱은 구 체계의 과세요건(3분류)을 구현하지 않는다. 현행 30% 요건으로 계산하면
 *      구법상 비대상인 법인에 **없는 세금을 만든다**(예: 지배주주 40% · 결손 없음 · 정상영업).
 *      「법 근거 없이 불리하게 적용하지 않는다」 ⇒ 계산하지 않고 **차단**한다.
 *
 * ② **위임 시행령 부재 구간(2020-01-01~02-10)** — 법 ①②는 시행 중이나 이익·한도의 계산방법을
 *    정한 영 §34의5(대통령령 제30391호)는 **2020-02-11** 시행이다. 법 §45의5③이 「대통령령으로
 *    정한다」고 위임한 사항이 존재하지 않는 구간이라 산식을 단정할 수 없다 ⇒ **차단**한다.
 *
 * ③ **net 구간(2020-02-11~2022-02-14)** — 그 시점 영 §34의5⑨ verbatim:
 *    「증여세 상당액은 같은 조 제1항의 증여일에 같은 항에 따른 **증여의제이익을** 해당 주주가
 *     직접 증여받은 것으로 볼 때의 증여세로 하고 …」 ⇒ base = 증여의제이익(법인세 차감 **後**).
 *    현행(대통령령 제32414호, 시행 2022-02-15) verbatim:
 *    「… **제4항제1호의 금액에** 해당 지배주주등의 주식보유비율을 **곱한 금액을** 해당 주주가
 *     직접 증여받은 것으로 볼 때의 증여세로 하고 …」 ⇒ base = 거래이익(법인세 차감 **前**) × 보유비율.
 *
 * ⚠️ net 구간에서는 ㉠의 base가 ㉮의 base와 «같아지므로» ㉠ = ㉮가 되고, 따라서
 *    한도액 ㉯ = ㉮ − ㉡ 가 되어 **법인세 상당액이 0이 아니면 항상 한도가 걸린다**.
 *    gross로 계산해 두면 그만큼 세액이 과대해진다(납세자 불리).
 */

/** 영 §34의5 최초 시행 — 대통령령 제30391호(2020-02-11). 그 전은 계산방법 위임이 비어 있다. */
export const SC_DECREE_EFFECTIVE_FROM = "2020-02-11";

/** 영 §34의5⑨ 증여세 상당액 base가 gross로 바뀐 날 — 대통령령 제32414호(2022-02-15). */
export const SC_LIMIT_GROSS_FROM = "2022-02-15";

/** 법 §45의5② 한도 신설 — 법률 제16846호(2020-01-01). 그 전에는 한도 규정 자체가 없었다. */
export const SC_LIMIT_INTRODUCED_FROM = "2020-01-01";

/** §45의5② 한도의 ㉠(증여세 상당액) 산정 기준 */
export type ScLimitBasis = "net" | "gross";

/**
 * 거래일(증여일)에 시행 중이던 영 §34의5⑨의 기준.
 * 거래일 미전달이면 현행(gross) — 무회귀 안전판이다(종전 동작과 같다).
 */
export function resolveScLimitBasis(transactionDate?: string): ScLimitBasis {
  if (!transactionDate) return "gross";
  return transactionDate.slice(0, 10) < SC_LIMIT_GROSS_FROM ? "net" : "gross";
}

/**
 * 이 앱이 계산할 수 없는 시점인지 판정한다. 반환값이 있으면 그것이 차단 사유다.
 *
 * 「현행 산식으로 조용히 계산」은 선택지가 아니다 — 구 체계 구간에서는 과세요건 자체가
 * 달라 없는 세금을 만들 수 있고(납세자 불리), 위임 부재 구간에서는 산식이 법정돼 있지 않다.
 */
export function resolveScEraExclusion(transactionDate?: string): string | undefined {
  if (!transactionDate) return undefined; // 미전달은 현행으로 본다(종전 동작 유지)
  const d = transactionDate.slice(0, 10);
  if (d < SC_LIMIT_INTRODUCED_FROM) {
    return `${d} 거래는 구 §45의5(법률 제16102호) 적용 대상입니다 — 당시 특정법인은 「결손법인·휴폐업법인·지배주주등 50% 이상 법인」 3가지였고 §45의5②의 증여세 한도 규정도 없었습니다. 이 화면은 현행(지배주주등 30%) 체계만 계산합니다.`;
  }
  if (d < SC_DECREE_EFFECTIVE_FROM) {
    return `${d} 거래는 법 §45의5①②(2020-01-01 시행)는 적용되나 이익·한도의 계산방법을 정한 상증령 §34의5(대통령령 제30391호)가 ${SC_DECREE_EFFECTIVE_FROM}부터 시행이라, 그 사이 거래의 산식이 법령에 정해져 있지 않습니다. 이 화면은 계산하지 않습니다.`;
  }
  return undefined;
}
