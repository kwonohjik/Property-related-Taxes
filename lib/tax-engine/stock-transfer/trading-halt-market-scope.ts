/**
 * 거래정지·관리종목 우회(영 §165③)가 적용되는 **시장 범위** — 단일 정본
 *
 * ## 왜 시장으로 갈리는가
 *
 * 법 §99①3은 §94①3가목 주식등(= 주권상장법인 주식)을 상증법 §63①1가목(1개월 종가평균)으로
 * 평가하되, 괄호로 「**대통령령으로 정하는 주권상장법인**의 주식등은 대통령령으로 정하는
 * 것만 해당한다」고 한정한다. 그 둘을 영 §165③이 채운다:
 *
 *   · 「대통령령으로 정하는 주권상장법인」 = **코스닥시장 또는 코넥스시장**에 주권을 상장한 법인
 *   · 「대통령령으로 정하는 것」          = **상증령 §52의2③**에 해당하는 것
 *       = 「매매거래가 정지되거나 관리종목으로 지정된 기간의 일부 또는 전부가 포함되는
 *          주식등…을 **제외한** 주식등」 (기간은 §165③ 후단이 「양도일·취득일 이전 1개월」로 치환)
 *
 * 즉 **코스닥·코넥스** 상장주가 거래정지·관리종목이면 §99①3에서 빠지고,
 * 법 §99①4 **전단**이 「제3호에 따른 대통령령으로 정하는 주권상장법인의 주식등 중 제3호에
 * 해당하지 아니하는 것」으로 그것을 받아 영 §165④ 보충평가로 보낸다.
 *
 * ## 코스피(유가증권시장)는 그 경로가 없다 — 두 논거
 *
 * **① 공백 논거.** §99①4 전단의 대상은 ⓐ「코스닥·코넥스 상장주 중 3호 비해당」과
 * ⓑ「§94①3**나목**(주권비상장법인) 주식등」 둘뿐이다. 코스피 상장주는 §94①3**가목**이라
 * ⓐ도 ⓑ도 아니다. 코스피 거래정지주가 §99①3에서도 빠진다고 보면 **§99① 어느 호에도
 * 속하지 않아 기준시가 산정 근거가 사라진다**. §99①은 「기준시가는 다음 각 호에서 정하는
 * 바에 따른다」로 망라적이고 §99③의 보충 위임에도 주식 공백을 메우는 호가 없다.
 *
 * **② 잉여 논거.** 상증법 §63①1가목 **준용만으로** 상증령 §52의2③ 필터가 딸려온다면,
 * 영 §165③이 그 필터를 「각각 코스닥시장 또는 코넥스시장」에 **한정해** 지정한 문언이
 * 잉여가 된다. 입법자가 두 시장에만 붙였다는 것은 준용 경로로는 딸려오지 않는다고 본 것이다.
 *
 * ⇒ **코스피 상장주식은 거래정지·관리종목이어도 §99①3(1개월 종가평균) 그대로다.**
 *
 * ⚠️ 해석례는 찾지 못했다(국세청 법령해석·조세심판원 검색 0건). 없다는 증명이 아니라
 *    검색 실패이며, 위 두 문리 논거로 판정했다. anchor: `stock-kospi-halt-scope.anchor.test.ts`
 *
 * ## 사용
 *
 * ⑤ UI(옵션 disable) · ⑧ validate · ④ API 변환 · ⑫ Zod refine 이 **모두 이 함수**를 부른다.
 * 손으로 `=== "kosdaq" || === "konex"` 를 다시 적지 말 것 — 네 층이 갈리면 그중 하나만
 * 열려도 세액이 조용히 달라진다(실측: 5억 양도에서 ±400만원대).
 */
export function isTradingHaltBypassMarket(marketType: string | undefined): boolean {
  return marketType === "kosdaq" || marketType === "konex";
}

/**
 * 거래정지 플래그가 **법령상 성립할 수 없는** 시장인가.
 *
 * ⚠️ 「우회 시장이 아니다」(`!isTradingHaltBypassMarket`)와 **같지 않다** — 비상장이 갈린다.
 *   · 코스피   → 위반. §99①3(종가평균) 그대로여야 하는데 플래그가 서면 §165④로 샌다.
 *   · 비상장   → **위반 아님**. 애초에 §99①4 대상이라 자기 경로로 §165④를 타므로
 *                플래그가 서든 안 서든 같은 값이다(엔진 `:165`·`:212` 둘 다 `calcUnlistedValuation`).
 *                여기서 거부하면 기존 stale 조합 테스트·API 호출을 근거 없이 깨뜨린다.
 *   · 기타자산·국외주식·국외전출 → 이 축의 판단 대상이 아니다.
 *
 * ⇒ **상장 시장 중 코스닥·코넥스가 아닌 것**만 위반이다.
 */
export function isTradingHaltMarketScopeViolation(marketType: string | undefined): boolean {
  const isListed = marketType === "kospi" || marketType === "kosdaq" || marketType === "konex";
  return isListed && !isTradingHaltBypassMarket(marketType);
}

