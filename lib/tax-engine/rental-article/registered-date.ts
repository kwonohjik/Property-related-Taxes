/**
 * 지자체 임대사업자 「등록일」(V-3) — 법문이 「등록을 한」·「등록한」인 경계와 기산에 쓴다.
 *
 * - 소령 §167의3①2호 가목 1)·다목 단서 「2018년 3월 31일까지 사업자등록등」: 서면-2021-법규재산-3280(2025.12.10.)은
 *   구청 신청 2018.3.30.·등록 2018.4.4.인 주택을 가목이 아니라고 봤다(신청일이 아니라 등록일).
 * - 같은 조 ③ 「사업자등록등을 하고 임대주택으로 등록하여 임대하는 날부터」·나목 「기존사업자기준일 이전에 사업자등록등」·
 *   부칙<제35349호> 제15조 「민간임대주택으로 등록한」·민특령 §34①2호 「임대사업자 등록일」.
 * 「등록 신청」 경계(⑳ 본문·마목 2) 2020.7.11.·부칙<제31083호> 제5조 2020.8.18.)는 신청일 그대로다.
 *
 * 등록일이 없으면(직접 API·옛 기록) 신청일로 본다 — 화면은 ⑧이 등록일을 필수로 막는다.
 */
export function registeredDateOf(
  registered: Date | null | undefined,
  application: Date | null | undefined,
): Date | null {
  const t = registered?.getTime?.();
  if (t != null && !Number.isNaN(t)) return registered!;
  return application ?? null;
}
