/** BX04 — 상가 부수토지가 있는 단서(분리) 경로. 정착면적은 건축면적이라 지방세법 시행령 제101조의 「바닥면적」과 같다고 보면 안 된다(서면-2018-부동산-3849는 정착면적 = 건축면적). */
export function mixedCommercialLandUnjudgedNotice(commercialLandArea: number): string | undefined {
  if (!(commercialLandArea > 0)) return undefined;
  return (
    `상가 부수토지(${commercialLandArea}㎡)는 비사업용 토지 기준면적을 판정하지 않습니다 — 「소득세법」 제104조의3 제1항 제4호 나목은 별도합산과세대상 토지를 제외하며, ` +
    "건축물 부속토지의 그 범위는 「지방세법 시행령」 제101조 제1항 제2호·제2항(건축물의 바닥면적 × 용도지역별 적용배율)입니다. " +
    "범위를 넘는 부분이 있으면 비사업용 토지(+10%p·장기보유특별공제 배제)가 될 수 있으나 이 계산은 그 부분을 가르지 않았습니다(확인 필요). 이 판정에는 정착면적이 아닌 건축물의 바닥면적이 필요합니다."
  );
}

/** BX05 — OH-17(§154③ 본문)로 상가 부수토지까지 주택 배율 초과분으로 옮긴 경로. */
export function mixedWholeBuildingLandBasisNotice(multiplier: number): string {
  return (
    `건물 전부를 주택으로 보는 경우(시행령 §154③ 본문) 상가 부수토지까지 주택 부속토지로 보아 건물 전체 정착면적 × ${multiplier}배를 넘는 부분을 비사업용 토지로 과세했습니다. ` +
    "「소득세법」 제104조의3 제1항 제5호의 주택부속토지는 「지방세법」 제106조제2항에 따르고, 같은 항 제1호는 1동 건물의 부속토지를 주거·주거 외 면적비율로 안분합니다. " +
    "그래서 상가 부수토지에도 주택 배율을 적용하는 것이 맞는지는 정면 해석례를 확인하지 못했습니다(확인 필요)."
  );
}
