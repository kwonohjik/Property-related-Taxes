/**
 * 「소득세법 시행령」 §156의2④⑤ · §156의3③ — **신축주택 완성 후 기한**과 **④의 1년 요건** 연혁
 * (OH-30 · OH-30b · E-5 대체주택 공용. 개정 없는 확정 역사 데이터. 정적 상수.)
 *
 * 계획서 `docs/00-pm/one-house-exemption-fix.plan.md` §3.3. 본문·부칙은 법제처 DRF 실독(2026-09-26).
 *
 * ## ① 완성 후 기한 — 2년 → 3년 (양도일 기준)
 *
 * 2021-02-17 시행본(MST 229391)·2023-01-01 시행본(MST 247489)의 §156의2④1·2호·⑤2·3호와 §156의3③1·2호는
 * 「완성된 후 **2년** 이내」다. 대통령령 제33267호(MST 248191, 2023-02-28)가 3년으로 바꿨고, 부칙 제8조가
 * 적용 시점을 양도일로 정했다:
 * > ① 제155조제1항, 제156조의2제4항제1호ㆍ제2호, 같은 조 제5항제2호ㆍ제3호 및 제156조의3제3항제1호ㆍ
 * >    제2호의 개정규정은 2023년 1월 12일 이후 주택을 양도하는 경우부터 적용한다.
 * > ② 2023년 1월 12일 전에 주택을 양도한 경우에는 … 종전의 규정에 따른다.
 * ⇒ ④(입주권)·⑤(대체주택)·§156의3③(분양권)이 **같은 부칙 조항**을 공유하므로 한 함수로 묶는다.
 *
 * ## ② ④의 「종전주택 취득 후 1년이 지난 후 권리 취득」 요건 — 권리 취득일 기준
 *
 * 2021-02-17 시행본 ④ 본문은 「…조합원입주권을 취득한 날부터 3년이 지나 종전의 주택을 양도하는
 * 경우로서…」 — **1년 문언이 없다**(③에는 그 전부터 있다). 대통령령 제32420호(2022-02-15 공포·시행)가
 * ④ 각 호 외의 부분에 1년 요건을 넣었고, 부칙 제12조가 경과조치를 둔다:
 * > 이 영 시행 전에 조합원입주권 또는 분양권을 취득한 경우의 1세대1주택 특례 적용에 관하여는
 * > 제156조의2제4항 각 호 외의 부분 또는 제156조의3제3항 각 호 외의 부분의 개정규정에도 불구하고
 * > 종전의 규정에 따른다.
 */

/** 대통령령 제33267호 부칙 제8조 — 완성 후 기한 3년이 적용되는 첫 양도일. */
export const COMPLETION_DEADLINE_3Y_TRANSFER_START = new Date("2023-01-12");
/** 대통령령 제32420호 시행일 — 이 날 이후 취득한 권리부터 ④에 1년 요건 (부칙 제12조). */
export const CLAUSE4_ONE_YEAR_RULE_RIGHT_START = new Date("2022-02-15");

/** 「(신축)주택이 완성된 후 N년 이내」의 N — §156의2④1·2호 · ⑤2·3호 · §156의3③1·2호. */
export function resolve1562DeadlineYears(transferDate: Date): 2 | 3 {
  return transferDate.getTime() >= COMPLETION_DEADLINE_3Y_TRANSFER_START.getTime() ? 3 : 2;
}

/** §156의2④ · §156의3③에 「종전주택 취득 후 1년이 지난 후 권리 취득」 요건이 붙는가 — 권리 취득일 기준. */
export function clause4RequiresOneYearGap(rightAcquisitionDate: Date): boolean {
  return rightAcquisitionDate.getTime() >= CLAUSE4_ONE_YEAR_RULE_RIGHT_START.getTime();
}
