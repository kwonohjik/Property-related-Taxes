/**
 * 「소득세법」 §95② 괄호 — **비사업용 토지가 장기보유특별공제 배제 자산이었던 시기**
 * (개정 없는 확정 역사 데이터. 정적 상수.)
 *
 * §95②는 본문 괄호로 일부 자산을 장기보유특별공제(LTHD) 대상에서 뺀다. 그 **괄호의 내용이
 * 시기마다 달랐고**, 비사업용 토지는 2016.1.1.에 빠졌다.
 * KoreanLaw `legal_analysis(mode=applicable_law)` 시행일별 본문 실측:
 *
 * | 시행일 | §95② 괄호 = 배제 자산 | 비사업용 토지 |
 * |---|---|---|
 * | 2007.1.1~2011.12.31 | "제104조제1항제4호부터 제10호까지의 규정에 따른 세율을 적용받는 자산 **및 제104조제6항을 적용받는 자산**은 제외한다" | **배제** (비사토 = §104①8호. 중과유예 §104⑥ 적용분도 명문 배제) |
 * | 2012.1.1~2015.12.31 | "제104조제3항에 따른 미등기양도자산 **및 제104조의3에 따른 비사업용 토지**는 제외한다" | **배제** (직접 명시) |
 * | 2016.1.1~ | "제104조제3항에 따른 미등기양도자산은 제외한다" | **적용** |
 * | 2018.4.1~ | "… 미등기양도자산과 같은 조 제7항 각 호에 따른 자산은 제외한다" | **적용** (§104⑦은 다주택 축) |
 *
 * 같은 구간 구분이 `lthd-multi-house-exclusion-era.ts`의 DRF 실측 표에도 그대로 적혀 있다
 * (그 leaf는 **다주택 축**만 판정하고 비사업용 축에는 배선되지 않았다 — 이 파일이 그 짝이다).
 *
 * ## §95④ 단서 — 2016년 한 해만 있었던 기산일 특례
 *
 * 2016.1.1. 개정(법률 제13558호)은 §95② 괄호에서 비사토를 빼면서 §95④에 단서를 함께 신설했다:
 *   「… 제104조의3에 따른 비사업용 토지로서 **2016년 1월 1일 이전에 취득**하여 보유하고 있는
 *     자산인 경우에는 **2016년 1월 1일부터 기산**한다」 (2016.1.25. 시행본 본문 확인)
 * 그리고 2017.1.1. 개정(법률 제14389호)에서 그 단서가 **삭제**됐다(2017.3.28. 시행본 본문 확인)
 * — 이후로는 취득일 기산으로 환원된다.
 *
 * ⚠️ **이 파일은 「그 시기의 §95②·§95④가 비사업용 토지를 어떻게 다뤘는가」라는 사실만 말한다.**
 *    실제로 그 자산이 비사업용인지는 `non-business-land/engine.ts`의 판정 결과이고,
 *    여기서는 판정하지 않는다 — `lthd-multi-house-exclusion-era.ts`와 같은 설계다.
 */

/** 비사업용 토지가 §95② 괄호에서 빠진 날 — 이 날부터 LTHD가 적용된다. */
export const NBL_LTHD_EXCLUSION_LIFTED = "2016-01-01";

/** §95④ 비사업용 토지 기산 단서가 삭제된 날 — 이 날부터 취득일 기산으로 환원. */
export const NBL_LTHD_ACQ_ANCHOR_SUNSET = "2017-01-01";

/**
 * 그 시점의 §95② 괄호가 **비사업용 토지를 LTHD에서 배제했는지**.
 *
 * @param transferDate 양도일
 * @returns `true`이면 그 시점엔 비사업용 토지가 배제 자산이었다.
 */
export function isNblLthdExclusionEra(transferDate: Date): boolean {
  return transferDate < new Date(NBL_LTHD_EXCLUSION_LIFTED);
}

/**
 * §95④ 단서(2016.1.1. 기산)가 적용되는지 — **2016년 양도분 + 2016.1.1. 이전 취득**에 한정.
 *
 * 단서는 2016.1.1. 신설 → 2017.1.1. 삭제라 창이 딱 1년이다. 취득일이 2016.1.1. 이후면
 * 취득일 기산과 결과가 같으므로 단서를 탈 필요가 없다.
 *
 * @returns `true`이면 보유기간을 2016-01-01부터 기산한다.
 */
export function usesNbl2016LthdAnchor(transferDate: Date, acquisitionDate: Date): boolean {
  const lifted = new Date(NBL_LTHD_EXCLUSION_LIFTED);
  const sunset = new Date(NBL_LTHD_ACQ_ANCHOR_SUNSET);
  return transferDate >= lifted && transferDate < sunset && acquisitionDate <= lifted;
}
