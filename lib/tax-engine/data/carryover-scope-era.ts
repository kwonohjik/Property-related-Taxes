/**
 * 배우자등 이월과세(§97의2①) — **대상 자산·기간의 시행 시기 게이트**
 * (개정 없는 확정 역사 데이터. 정적 상수.)
 *
 * §104②2호는 「**제97조의2제1항에 해당하는 자산**」을 증여자 취득일로 소급시킨다.
 * 따라서 ①의 **대상 자산 범위가 넓어지면 §104②2호도 함께 넓어진다.**
 * 2025.1.1.부터 **주식등(§94①3호)**이 ①에 포섭되면서 그 일이 실제로 일어났다.
 *
 * ── 연혁 대조 실측 (`target=eflaw` + `LM=소득세법` + `efYd`) ──────────────
 *
 * | 시행본 | §97의2① 각 호 외의 부분 |
 * |---|---|
 * | 2024-01-01 | "10년 이내에 … 증여받은 **제94조제1항제1호**에 따른 자산이나 그 밖에 대통령령으로 정하는 자산" |
 * | 2025-01-01 | "10년(**제94조제1항제3호에 따른 자산의 경우에는 1년**) 이내에 … 증여받은 **제94조제1항제1호 및 제3호**에 따른 자산이나 …" \<개정 2024.12.31\> |
 *
 * **부칙 법률 제20615호(2024.12.31. 공포)** (법제처 DRF 부칙 실측):
 * > 제1조(시행일) 이 법은 **2025년 1월 1일**부터 시행한다.
 * > 제8조(양도소득의 필요경비 계산 특례에 관한 적용례) 제97조의2제1항 **각 호 외의 부분**의
 * > 개정규정은 이 법 시행 이후 **증여받는 자산부터** 적용한다.
 *
 * "증여받는 자산부터"이므로 기준은 **증여일**이지 양도일이 아니다.
 * ⚠️ 같은 조의 다른 개정은 축이 다르다 — 법률 제19933호(2023.12.31) 부칙 §8은
 *    "이 법 시행 이후 **자산을 양도하는 경우**부터". **개정마다 적용례 축이 다르므로 재사용 금지.**
 *
 * ── 기간 요건 ─────────────────────────────────────────────────────────
 * §97의2① 괄호가 자산 종류별로 다른 기간을 정한다 —
 * 부동산등은 **10년**, §94①3호 주식등은 **1년**.
 *
 * 설계: `docs/02-design/features/transfer-104-2-2-gift-carryover-scope.plan.md` §2 ⑥
 */

/**
 * 주식등(§94①3호)이 §97의2① 대상이 되는 **최초 증여일**
 * (부칙 법률 제20615호 §1·§8 — 시행일 2025.1.1. + "시행 이후 **증여받는** 자산부터").
 */
export const CARRYOVER_STOCK_GIFT_GATE = "2025-01-01";

/** §97의2① 「양도일부터 소급하여 N년 이내」의 N — 자산 종류별로 다르다. */
export const CARRYOVER_PERIOD_YEARS = {
  /** 부동산등 (§94①1호 및 영 §163의2① 자산) */
  realEstate: 10,
  /** 주식등 (§94①3호) — 2025.1.1. 이후 증여분 */
  stock: 1,
} as const;

/**
 * 주식 증여가 §97의2①(따라서 §104②2호)의 시기 요건을 충족하는가.
 * **증여일** 기준이다 — 양도일로 판정하면 개정 전 증여분까지 소급 통산하게 된다.
 */
export function isStockCarryoverEra(giftDate: Date): boolean {
  return giftDate >= new Date(CARRYOVER_STOCK_GIFT_GATE);
}

/**
 * §97의2① 「양도일부터 소급하여 N년 이내에 증여받은」 기간 요건 충족 여부.
 *
 * ⚠️ 세율 축(§104②2호)에서 주식의 1년 요건은 **결과를 바꾸지 않는다** —
 * 「증여 후 1년 초과」와 「수증일 기산 1년 이상」이 같은 조건이라, 요건을 빠뜨려도
 * §104①11호가목2)로 귀결된다. 그래도 법령대로 판정한다(§97의2① 본체에서는 실제로 갈린다).
 */
export function isWithinCarryoverPeriod(
  giftDate: Date,
  transferDate: Date,
  kind: keyof typeof CARRYOVER_PERIOD_YEARS,
): boolean {
  const limit = new Date(giftDate);
  limit.setFullYear(limit.getFullYear() + CARRYOVER_PERIOD_YEARS[kind]);
  return transferDate <= limit;
}
