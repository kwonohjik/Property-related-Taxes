/** 60항목 체계(2018~2026 동일 번호) 적용 연도 범위 (전사 완료분) */
const USAGE_60_YEARS_DONE = new Set([2018, 2019, 2020, 2021, 2022, 2023, 2024, 2025, 2026]);

export const USAGE_INDEX_MIN_YEAR = 2001;
export const USAGE_INDEX_MAX_YEAR = 2026;

/** 해당 연도 용도지수 전사 완료 여부 */
export function hasUsageIndexYear(year: number): boolean {
  return USAGE_60_YEARS_DONE.has(year);
}

/**
 * (연도, 용도번호 1~60) → 용도지수(정수). 미전사 연도/미존재 번호 = undefined(검증 오류 처리).
 * #61(기계식주차)은 일반 용도지수 아님 → resolveMechParkingFormula(D9) 사용.
 */
export function resolveUsageIndex(year: number, usageNo: number): number | undefined {
  if (!USAGE_60_YEARS_DONE.has(year)) return undefined; // 전사 대기 연도
  const override = USAGE_OVERRIDE_60[year];
  if (override && usageNo in override) return override[usageNo];
  return USAGE_INDEX_2026[usageNo];
}

/** UI 드롭다운용 — 해당 연도 용도 옵션(번호·표시명·지수). #61(기계식)은 제외(별도 토글). */
export function listUsageOptions(
  year: number,
): ReadonlyArray<{ no: number; label: string; index: number }> {
  if (!USAGE_60_YEARS_DONE.has(year)) return [];
  const out: { no: number; label: string; index: number }[] = [];
  for (let no = 1; no <= 60; no++) {
    const idx = resolveUsageIndex(year, no);
    if (idx !== undefined) out.push({ no, label: USAGE_LABELS[no], index: idx });
  }
  return out;
}
