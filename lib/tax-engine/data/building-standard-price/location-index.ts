interface YearTable {
  boundaries: readonly number[];
  rates: readonly number[];
}

/** 연도 → {경계, 지수배열} 조회. 보유 범위 밖이면 undefined(R11 — 2026 등) */
function resolveYearTable(year: number): YearTable | undefined {
  if (INDEX_45[year]) return { boundaries: BOUNDARIES_45, rates: INDEX_45[year] };
  if (INDEX_25[year]) return { boundaries: BOUNDARIES_25, rates: INDEX_25[year] };
  if (INDEX_13[year]) return { boundaries: BOUNDARIES_13, rates: INDEX_13[year] };
  if (INDEX_11[year]) return { boundaries: BOUNDARIES_11, rates: INDEX_11[year] };
  if (INDEX_5[year]) return { boundaries: BOUNDARIES_5, rates: INDEX_5[year] };
  // 2000년 이전 = 2001년표 적용(고시 §6① — 2001.1.1 공시지가 기준)
  if (year < 2001) return { boundaries: BOUNDARIES_5, rates: INDEX_5[2001] };
  return undefined;
}

export const LOCATION_INDEX_MIN_YEAR = 2001;
export const LOCATION_INDEX_MAX_YEAR = 2026;

/** 위치지수 데이터 보유 연도 여부 */
export function hasLocationIndexYear(year: number): boolean {
  return resolveYearTable(year) !== undefined;
}

/**
 * (연도, ㎡당 공시지가) → 위치지수(정수). 보유 범위 밖 연도면 undefined(검증 오류 처리).
 * 구간은 "이상~미만" — landPricePerM2가 속한 가장 높은 하한 구간의 지수.
 */
export function resolveLocationIndex(year: number, landPricePerM2: number): number | undefined {
  const table = resolveYearTable(year);
  if (!table) return undefined;
  let idx = 0;
  for (let i = 0; i < table.boundaries.length; i++) {
    if (landPricePerM2 >= table.boundaries[i]) idx = i;
    else break;
  }
  return table.rates[idx];
}
