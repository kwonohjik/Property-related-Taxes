/** 국외주식 §94①3호다목 트랙 개시일 — 이 날 **이후 양도분**부터 적용(부칙 §1·§2②). */
export const FOREIGN_STOCK_TRACK_START = "2020-01-01";

/**
 * 양도일이 §94①3호다목 트랙 개시일 **이전**인가 (= 이 앱이 지원하지 않는 구간).
 *
 * 인자는 **사실(양도일)만** 받는다 — 모드 플래그·시장 종류를 받지 않는다.
 * 빈 문자열·파싱 불가 값은 **false**(여기서 막지 않는다) — 필수값 누락은 별도 검증의 몫이다.
 */
export function isBeforeForeignStockTrack(transferDate: Date | string | undefined): boolean {
  if (!transferDate) return false;
  const d = transferDate instanceof Date ? transferDate : new Date(transferDate);
  if (Number.isNaN(d.getTime())) return false;
  return d < new Date(FOREIGN_STOCK_TRACK_START);
}
