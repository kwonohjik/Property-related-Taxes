/** 연도별 세율 구간 — 분모 10000 고정 */
export interface StxRatePeriod {
  /** 구간 시작일 (양도일 >= from) — "YYYY-MM-DD" */
  from: string;
  /** 구간 종료일 (양도일 <= to). null = 현행 개방 구간 */
  to: string | null;
  /** 코스피 (시행령 §5 1호) */
  kospiNum: number;
  /**
   * 코스닥 (현행 시행령 §5 3호 가목)
   *
   * 🔑 **K-OTC 와 분리돼 있다.** 2021.1.1~ 현재는 두 시장이 같은 호의 가·나목이라 항상 동률이지만,
   *    **2017.3.31 이전에는 §5 에 협회 경유(K-OTC) 목이 자체가 없었다** — 그 구간의 K-OTC 는
   *    탄력세율 대상이 아니라 법 §8① 본칙이다. 한 칸으로 묶으면 그 구간을 표현할 수 없다.
   */
  kosdaqNum: number;
  /** K-OTC — 금융투자협회 경유 양도 (현행 시행령 §5 3호 나목). 위 `kosdaqNum` 주석 참조 */
  kotcNum: number;
  /** 코넥스 (시행령 §5 2호) */
  konexNum: number;
  /** 비상장 장외 (법 §8① — 한시 단서 반영) */
  unlistedNum: number;
  /** 시행령 §5 구간 인용 suffix (rateReference 조합용) */
  refSuffix: string;
  /** 비상장(법 §8①) 구간 인용 */
  unlistedRef: string;

  /**
   * 시행령 §5 의 **호·목 구조가 현행과 다른 구간**의 인용 override.
   *
   * `legal-codes/stock.ts` 의 `STX_DECREE_5_*` 상수는 **현행(2021.1.1~) 구조**를 적는다
   * (1호 코스피 / 2호 코넥스 / 3호 가·나 코스닥·K-OTC). 그런데 §5 는 호·목이 여러 번
   * 재배치됐다 — 2019.6.3~2020.12.31 은 「1호 가·나 = 코스피·코넥스, 2호 가·나 =
   * 코스닥·K-OTC」이고, 2017.4.1~2019.6.2 는 「2호 가·나·다 = 코스닥·코넥스·K-OTC」다.
   * 그 구간에 현행 구조 상수를 그대로 붙이면 **없는 호를 인용**하게 된다(예: 2018년 양도에
   * 「§5 3호 가목」 — 당시 §5 에 3호가 없다).
   *
   * ⇒ 구조가 다른 구간만 여기에 축자 인용을 적고, 미지정이면 현행 구조 상수를 쓴다.
   *    세율 **값**이 아니라 **인용 문자열**이므로 계산에는 영향이 없다.
   */
  kospiRef?: string;
  kosdaqRef?: string;
  konexRef?: string;
  kotcRef?: string;
}

