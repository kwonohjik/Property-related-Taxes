/**
 * 혼인 전 소유한 주택분양권으로 주택을 취득할 때 **다른 배우자의 주택**을 주택 수에서 빼는 근거의 연혁
 * (취득세 — PR #1839 후속). 개정 없는 확정 역사 데이터.
 *
 * 법제처 DRF 실독 2026-09-30:
 *  - 대통령령 제33308호(2023.2.28. 시행, MST 248313) §28의4⑤ — 1~4호뿐(배우자 주택 제외 규정 없음)
 *  - 대통령령 제33325호(2023.3.14. 공포·시행, MST 248737) §28의4⑤6호 신설 — 「혼인한 사람이 혼인 전
 *    소유한 주택분양권으로 주택을 취득하는 경우 다른 배우자가 혼인 전부터 소유하고 있는 주택」
 *    부칙 제2조: 「제28조의2부터 제28조의4까지 … 의 개정규정은 이 영 시행 이후 납세의무가 성립하는
 *    분부터 적용한다.」 (취득세 납세의무 성립 = 취득하는 때 — 지방세기본법 §34①1호)
 *  - 2024.3.26. 개정 — 항 신설로 ⑥6호(현행 MST 288831), 문언 동일. 기한 부칙 없음(계획서 D-9b).
 *
 * ## 2023.3.14. 전 취득 — §28의4① 후단
 *
 * 6호가 없던 때에도 §28의4① 후단(「주택분양권의 취득일(분양사업자로부터 … 분양계약일)을 기준으로
 * 해당 주택 취득 시의 세대별 주택 수를 산정한다」)이 있었다. 조세심판원은 이를 **권리취득일 현재의
 * 세대**로 읽어, 권리취득 뒤 혼인한 배우자의 주택을 세지 않았다:
 *  - 조심 2023지4299(2024.3.5., 취소) — 2020.9.23. 분양계약 · 2021.3.10. 혼인 · 2023.1.30. 취득
 *  - 조심 2023지3598(2024.3.14., 취소) — 2021.5.12. 분양계약 · 2022.5.20. 혼인 · 2023.1.20. 취득
 *  (둘 다 「조심 2022지890, 2023.8.8. 결정 등 다수」를 인용. 처분청은 취득일 현재 세대로 셌다.)
 * 소급 산정은 2020.8.12. 이후 취득한 권리부터다(대통령령 제30939호 부칙 제2조) — 그 전 권리로 취득하면
 * 기준일이 주택 취득일이라 배우자가 세대에 있고, 뺄 근거가 없다.
 *
 * | 주택 취득일 | 소급 산정 | 연혁 | 효과 |
 * |---|---|---|---|
 * | ≥ 2023-03-14 | 무관 | `statute_6ho` | ⑥6호 — 혼인 전부터 소유한 배우자 주택 제외 |
 * | < 2023-03-14 | 예 | `right_date_household` | §28의4① 후단 — 권리취득일 현재 세대 밖 배우자 주택 제외 |
 * | < 2023-03-14 | 아니오 | `none` | 제외 없음 |
 */

import { ACQUISITION_CONST } from "../legal-codes";

export type PreMarriageSpouseHouseEra = "statute_6ho" | "right_date_household" | "none";

/**
 * @param acquisitionDate 취득하는 주택의 취득일 (YYYY-MM-DD)
 * @param isRightDateSoGup §28의4① 후단 소급 산정이 적용되는지(2020.8.12. 이후 취득한 권리)
 */
export function resolvePreMarriageSpouseHouseEra(
  acquisitionDate: string,
  isRightDateSoGup: boolean
): PreMarriageSpouseHouseEra {
  if (acquisitionDate >= ACQUISITION_CONST.PRE_MARRIAGE_RIGHT_FROM) return "statute_6ho";
  return isRightDateSoGup ? "right_date_household" : "none";
}
