/** 표의 세 행 */
export type EmployeeSportsFacilityKind = "field" | "court" | "indoor";

/**
 * 종업원수 `n`에 대한 시설별 기준면적(㎡).
 *
 * 운동장(`field`)만 구간 내 선형 가산이고 코트·실내는 계단식 고정이다.
 * 비고(50인 이하 코트만 · 실내 바닥면적 하한 · 용도지역 배율)는 **호출부가** 처리한다 —
 * 두 법령의 비고가 서로 다르기 때문이다(위 표).
 */
export function employeeSportsStandardArea(
  kind: EmployeeSportsFacilityKind,
  n: number,
): number {
  if (kind === "court") return n <= 500 ? 970 : n <= 2000 ? 1940 : 2910;
  if (kind === "indoor") return n <= 100 ? 150 : n <= 500 ? 300 : n <= 2000 ? 450 : 900;
  // field(운동장) — 구간 내 선형 가산
  if (n <= 100) return 1000;
  if (n <= 500) return 1000 + (n - 100) * 9;
  if (n <= 2000) return 4600 + (n - 500) * 3;
  if (n <= 10000) return 9100 + (n - 2000) * 1;
  return 17100;
}
