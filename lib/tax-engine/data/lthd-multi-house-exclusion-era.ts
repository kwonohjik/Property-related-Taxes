/**
 * 「소득세법」 §95② 괄호 — **다주택 중과 주택이 장기보유특별공제 배제 자산이었던 시기**
 * (개정 없는 확정 역사 데이터. 정적 상수.)
 *
 * §95②는 본문 괄호로 일부 자산을 장기보유특별공제(LTHD) 대상에서 뺀다. 그 **괄호의 내용이
 * 시기마다 달랐고**, 다주택 중과 주택은 두 번 들어왔다 나갔다 했다.
 * 법제처 DRF `target=eflaw`(`LM=소득세법`+`efYd`) 시행일별 실측:
 *
 * | 시행일 | §95② 괄호 = 배제 자산 | 다주택 |
 * |---|---|---|
 * | ~2011.12.31 | "제104조제1항제4호부터 제10호까지의 규정에 따른 세율을 적용받는 자산 및 제104조제6항을 적용받는 자산은 제외한다" | **배제** |
 * | 2012.1.1~2013.12.31 | "제104조제3항에 따른 미등기양도자산 및 제104조의3에 따른 비사업용 토지는 제외한다" | **가능** |
 * | 2014.1.1~2016.12.31 | (동일) | **가능** |
 * | 2017.1.1~2018.3.31 | "제104조제3항에 따른 미등기양도자산은 제외한다" | **가능** |
 * | 2018.4.1~ | "제104조제3항에 따른 미등기양도자산과 **같은 조 제7항 각 호에 따른 자산**은 제외한다" | **배제** |
 *
 * 이 구간 구분은 **국세청 사전-2024-법규재산-0161**(2024.5.3.)의 각주와 일치한다 —
 * "’12.1.1.～’18.3.31.까지 다주택자의 주택 양도에 대해 장기보유특별공제 가능".
 *
 * ⚠️ **이 표는 「그 시기의 §95② 괄호가 다주택을 배제할 수 있었는가」만 말한다.**
 *    실제로 배제됐는지는 조정대상지역 지정·주택 수·중과 유예 등 **사실 판정**이 따로 필요하다.
 *    (2018.4.1~ 구간의 §104⑦은 조정대상지역 요건을 담고 있다.)
 *    ⇒ 이 leaf는 **시기라는 사실만** 판정하고, 나머지는 호출자가 입력으로 받는다.
 *
 * ⚠️ **`multi-house-surcharge-rate-history.ts`와 축이 다르다.** 그쪽은 **중과 세율(가산율)**
 *    이고 "~2018.3.31 중과 미적용"이라 적혀 있는데, LTHD 배제 축에서는 **2012년 이전이
 *    배제기**였다. 두 상수를 서로 대신 쓰지 말 것.
 */

/** 다주택이 §95② 괄호에서 빠진 날 — 이 날부터 LTHD가 가능해졌다. */
export const MULTI_HOUSE_LTHD_EXCLUSION_LIFTED = "2012-01-01";

/** §104⑦ 각 호가 §95② 괄호에 들어온 날 — 이 날부터 다시 배제된다. */
export const MULTI_HOUSE_LTHD_EXCLUSION_RESTORED = "2018-04-01";

/**
 * 해당 시점의 §95② 괄호가 **다주택 중과 주택을 LTHD에서 배제할 수 있었는지**.
 *
 * @returns `false`이면 그 시점엔 다주택이어도 배제 자산이 될 수 없었다(= 기산일 이동 불가).
 *          `true`는 "배제될 수 있었다"이지 "배제됐다"가 아니다 — 사실 판정은 호출자 몫.
 */
export function isMultiHouseLthdExclusionEra(date: Date): boolean {
  const lifted = new Date(MULTI_HOUSE_LTHD_EXCLUSION_LIFTED);
  const restored = new Date(MULTI_HOUSE_LTHD_EXCLUSION_RESTORED);
  if (date < lifted) return true;
  if (date < restored) return false;
  return true;
}
