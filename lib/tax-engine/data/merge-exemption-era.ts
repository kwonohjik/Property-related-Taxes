export type MergeExemptionKind = "parental_care" | "marriage";

/** 동거봉양 합가 10년 — 대통령령 제28637호(2018-02-13 공포·시행) 이후 양도분. */
export const PARENTAL_CARE_MERGE_10Y_TRANSFER_START = new Date("2018-02-13");
/** 혼인 합가 10년 — 대통령령 제34990호(2024-11-12 공포·시행) 이후 양도분. */
export const MARRIAGE_MERGE_10Y_TRANSFER_START = new Date("2024-11-12");

/** 「합친 날(혼인한 날)부터 N년 이내에 먼저 양도하는 주택」의 N — **양도일** 기준. */
export function resolveMergeExemptionYears(kind: MergeExemptionKind, transferDate: Date): 5 | 10 {
  const start =
    kind === "marriage" ? MARRIAGE_MERGE_10Y_TRANSFER_START : PARENTAL_CARE_MERGE_10Y_TRANSFER_START;
  return transferDate.getTime() >= start.getTime() ? 10 : 5;
}
