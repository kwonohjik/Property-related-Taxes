/** 제27829호(2017-02-03 시행) — 이 날 이후 양도분부터 §155③ 「선순위 1주택」 한정이 적용된다. */
export const CO_INHERITED_RANKING_CLAUSE_START = new Date("2017-02-03");

/** 양도일이 §155③ 「선순위 1주택」 한정 신설(2017.2.3.) 전인가 — 같은 날(2017-02-03)은 적용 구간이다. */
export function isBeforeCoInheritedRankingClause(transferDate: Date): boolean {
  return transferDate.getTime() < CO_INHERITED_RANKING_CLAUSE_START.getTime();
}
