/**
 * 가업상속공제 자산 양도 특례 — **시행 시기 게이트**
 * (개정 없는 확정 역사 데이터. 정적 상수.)
 *
 * 두 게이트의 **기준일 축이 서로 다르다**. 섞으면 조용히 반대로 걸린다.
 *
 * | 게이트 | 대상 | 근거 | 기준 | 경계 |
 * |---|---|---|---|---|
 * | G-1 | 「소득세법」 §97의2④ 의제 취득가액 + **§95④ 후단**(LTHD 기산) | 부칙 법률 제12169호 §12 | **상속개시일** | 2014-01-01 |
 * | G-2 | 「소득세법 시행령」 §163의2③(적용률 산정)·④(대상 자산 범위) | 부칙 대통령령 제36129호 §10 | **양도일** | 2026-02-27 |
 *
 * **G-1 — 부칙 법률 제12169호 제12조** (법제처 DRF 부칙 실측):
 * > 제12조(양도소득의 필요경비 계산 특례에 관한 적용례) 제97조의2제4항 및 제5항의 개정규정은
 * > 이 법 시행 후 **상속받아** 양도하는 분부터 적용한다.
 *
 * "상속받아"이므로 기준은 **상속개시일**이지 양도일이 아니다.
 *
 * §95④ 후단은 부칙에 전용 적용례가 **없다**. 그러나 후단이 §97의2④1호의 **적용률을 참조**하므로,
 * §97의2④이 적용되지 않는 자산에는 적용률 자체가 정의되지 않아 후단이 작동할 수 없다.
 * ⇒ G-1 하나로 통합한다. 연혁 대조 실측(`target=eflaw` + `LM=소득세법` + `efYd`):
 *
 * | 시행본 | §95④ 단서 |
 * |---|---|
 * | 2013-01-01 | "다만, **제97조제4항의 경우에는** 증여한 배우자 또는 직계존비속이…" — 가업상속 문구 **없음** |
 * | 2014-01-01 | "… **같은 조 제4항제1호에 따른 가업상속공제가 적용된 비율에 해당하는 자산**의 경우에는 피상속인이 해당 자산을 취득한 날부터 기산한다." |
 *
 * **G-2 — 부칙 대통령령 제36129호 제10조** (법제처 DRF 부칙 실측):
 * > 제10조(양도소득의 필요경비 계산 특례에 관한 적용례) 제163조의2제3항 및 제4항의 개정규정은
 * > 이 영 시행 이후 **자산을 양도하는 경우**부터 적용한다.
 *
 * 시행령 §163의2④는 §97의2④의 **대상 자산 범위**를 개인가업=사업용 자산(상증령 §15⑤1호),
 * 법인가업=주식등(동 2호)으로 한정한다. G-2 이전 양도분에는 그 명문이 없고,
 * 대법원 2026두30294(2026.5.22 심리불속행)이 구법 사안에서 같은 결론을 냈다 —
 * "가업상속공제를 받은 주식과 아닌 주식으로 **구분·관리**하고 그중 공제받은 주식 양도 시에만 적용".
 *
 * ⚠️ 이 leaf는 **시기라는 사실만** 판정한다. 대상 자산 해당 여부(사업용 자산인지·공제받은
 *    주식인지)는 사실 판정이므로 호출자가 입력으로 받는다.
 *
 * 설계: `docs/02-design/features/transfer-fb-lthd-95-4-latter.plan.md` §3.3
 */

/** G-1 — §97의2④·§95④ 후단이 적용되는 최초 **상속개시일** (부칙 법률 제12169호 §12). */
export const FB_CGT_INHERITANCE_GATE = "2014-01-01";

/** G-2 — 시행령 §163의2③·④가 적용되는 최초 **양도일** (부칙 대통령령 제36129호 §10). */
export const FB_ASSET_SCOPE_DECREE_GATE = "2026-02-27";

/**
 * G-1 — 「소득세법」 §97의2④ 의제 취득가액과 §95④ 후단(LTHD 피상속인 기산)이 적용되는가.
 *
 * @param inheritanceDate **상속개시일** (양도일이 아니다 — 부칙 §12 "상속받아")
 */
export function isFamilyBusinessCgtEra(inheritanceDate: Date): boolean {
  return inheritanceDate >= new Date(FB_CGT_INHERITANCE_GATE);
}

/**
 * G-2 — 대상 자산 범위 판정 근거가 **시행령 §163의2④**인가, 아니면 판례(G-3)인가.
 *
 * @param transferDate **양도일** (상속개시일이 아니다 — 부칙 §10 "자산을 양도하는 경우")
 * @returns `true`면 시행령 §163의2④ 명문, `false`면 대법원 2026두30294 해석에 따른다.
 */
export function isFamilyBusinessAssetScopeDecreeEra(transferDate: Date): boolean {
  return transferDate >= new Date(FB_ASSET_SCOPE_DECREE_GATE);
}
