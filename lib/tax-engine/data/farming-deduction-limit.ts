/**
 * 영농상속공제 연도별 한도 (현행 상증법 §18의3① / 2022년 이전 §18②2호)
 *
 * 출처 — KoreanLaw 1차 검증 완료 (2026-06-04). 조세심판원 적용조문 축자 인용 +
 * 신구대조표(compare_old_new) + 연혁 신설조문으로 5개 한도 전부 확정.
 *   · 2억원: 조심2010중2776 (상속개시 2007.2.21) — §18②2호 "2억원을 한도로 한다"
 *   · 5억원: 조심2014중4319 (2012.2.20) · 조심2017중4714 (2013.11.8) — "5억원을 한도로 한다"
 *   · 15억원: 조심2019중4355 (2018.1.9) · 조심2023부7501 (2021.6.3) — "15억원을 한도로 한다"
 *   · 20억원: 법률 제18591호(시행 2022.1.1) 신구대조표 §18②2호 "15억원 → 20억원" +
 *            조심2024중3710 (상속개시 2022.6.7) — "20억원을 한도로 한다"
 *   · 30억원: 법률 제19195호(시행 2023.1.1, MST 247439) §18의3① 신설 — "30억원을 한도로 한다"
 *
 * ※ "20억원" 구간은 2022년 한 해(법률 제18591호로 15억→20억 인상) 실재 — 4단계가 아니라 5단계.
 *   2022.1.1 인상이 누락되면 2022년 사망 상속에서 영농상속공제 5억 과소공제·상속세 과다계산.
 *
 * 경계 시행일(전부 개정법으로 정확 확인): 30억=2023.1.1(제19195호) · 20억=2022.1.1(제18591호) ·
 *   15억=2016.1.1(제13557호) · 5억=2012.1.1 · 2억=floor(2011.12.31 이전).
 *
 * string(YYYY-MM-DD) 비교 — cohabitShareRate(inheritance-deductions.ts) 패턴 일관, Date 변환 금지.
 */

/** 영농상속공제 한도 개정 구간 — 내림차순(최신 우선). `from` 이상이면 해당 limit. */
export const FARMING_DEDUCTION_LIMIT_HISTORY: ReadonlyArray<{
  from: string;
  limit: number;
}> = [
  { from: "2023-01-01", limit: 3_000_000_000 }, // 30억 (현행 §18의3① — 법률 제19195호)
  { from: "2022-01-01", limit: 2_000_000_000 }, // 20억 (§18②2호 — 법률 제18591호·조심2024중3710)
  { from: "2016-01-01", limit: 1_500_000_000 }, // 15억 (§18②2호 — 조심2019중4355·2023부7501)
  { from: "2012-01-01", limit: 500_000_000 }, //   5억 (조심2014중4319·2017중4714)
  { from: "0000-01-01", limit: 200_000_000 }, //   2억 (2011.12.31 이전 — 조심2010중2776)
];

/**
 * 상속개시일(deathDate, YYYY-MM-DD string)별 영농상속공제 한도.
 * deathDate 미입력 시 현행 30억 (legacy 호환 — FARMING_MAX와 동일).
 */
export function resolveFarmingDeductionLimit(deathDate?: string): number {
  if (!deathDate) return 3_000_000_000;
  for (const tier of FARMING_DEDUCTION_LIMIT_HISTORY) {
    if (deathDate >= tier.from) return tier.limit;
  }
  return 3_000_000_000;
}
