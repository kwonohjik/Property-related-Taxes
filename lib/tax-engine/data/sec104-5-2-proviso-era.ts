/**
 * 「소득세법」 제104조 제5항 제2호 **단서**의 적용 시점 (정적 상수).
 *
 * > 다만, 둘 이상의 자산에 대하여 제1항 각 호, 제4항 각 호 및 제7항 각 호에 따른 세율 중 동일한 호의 세율이 적용되고, 그 적용세율이 둘 이상인 경우
 * > 해당 자산에 대해서는 각 자산의 양도소득과세표준을 합산한 것에 대하여 제1항ㆍ제4항 또는 제7항의 각 해당 호별 세율을 적용하여 산출한 세액 중에서
 * > 큰 산출세액의 합계액으로 한다.
 *
 * 적용 기준은 **양도일**이다 — 법률 제16104호(2018.12.31.) 부칙 제2조②가 «이 법 중 양도소득세에 관한 개정규정은 이 법 시행 후 양도하는 분부터
 * 적용한다»로 정한다(시행 2019.1.1. — 제1조 단서의 2020.1.1. 시행 목록에 제104조는 없다. KoreanLaw 부칙 원문 실독, 2026-10-18).
 *
 * | 양도일 | 단서 | 근거 |
 * |---|---|---|
 * | ~ 2018-12-31 | **없음** — 2018.4.1. 시행본(제15225호) §104⑤2호는 「자산별 양도소득 산출세액 합계액」뿐이다. 둘 이상의 호에 해당하는 자산은 합산하지 않고 자산마다 §104① 후단·⑦ 후단의 큰 세액을 더한다(β) | `get_law_text` efYd=20180601 |
 * | 2019-01-01 ~ | 적용 — 합산한 과세표준에 각 해당 호별 세율, 큰 세액 | 제16104호 부칙 제2조② |
 *
 * ⚖ 「명확화(그 전에도 같은 결과)」 독법은 채택하지 않는다 — 2026-10-18 사용자 결정(부칙 문언). 단일 호 자산의 호별 합산
 *   (본문 · 기획재정부 재산세제과-536)은 2019 전에도 그대로다.
 *
 * 계획서: `docs/02-design/features/transfer-104-5-2-proviso-era.plan.md`
 */
export const SEC104_5_2_PROVISO_FROM = "2019-01-01";

/** 로컬 달력 기준 일자 키 — UTC 변환(`toISOString`)은 KST 자정을 전날로 만든다(`nbl-rate-deferral-era.ts`와 같은 규약). */
const dayKey = (d: Date): string =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

/** 양도일(경계일 포함) 기준 적용 여부. 다건은 한 과세기간이라 모든 자산이 같은 쪽에 놓인다. */
export function isSec104_5_2ProvisoInForce(transferDate: Date): boolean {
  return dayKey(transferDate) >= SEC104_5_2_PROVISO_FROM;
}
