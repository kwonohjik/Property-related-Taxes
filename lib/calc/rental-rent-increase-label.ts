/**
 * 장기임대 감면 폼의 「임대료 증액 제한」 섹션 — 어느 조문이 묻는지·라벨·제목의 단일 소스.
 * UI(`RentalCommonFields` ⑤)·API(`transfer-tax-api-reductions.ts` ④)·validate(⑧)·E2E 필드 점프가 함께 쓴다.
 *
 * 임대료 증액 제한은 **§97의3·§97의4·§97의5에만** 있다 (KoreanLaw MCP 원문 실독 2026-11-01):
 *   · §97의3: 법 §97의3①2호 → 령 §97의3③1호 (5% 한도 + 1년 이내 재증액 금지)
 *   · §97의5: 법 §97의5①3호가 §97의3①2호 요건 준수를 요구
 *   · §97의4: 조특령 §97의4① → 소득세법 시행령 §167의3①2호 가·다목
 *   · §97(본문·단서)·§97의2: 법 §97①·§97의2①, 령 §97·§97의2 어디에도 임대료 요건이 없다 → 섹션을 묻지 않는다.
 *     종전에는 다섯 조문 폼이 모두 묻고 미선택이면 ⑧이 막았지만 평가기는 그 답을 읽지 않았다.
 */
export function hasRentIncreaseRule(type: string): boolean {
  return type === "rental_97_3" || type === "rental_97_4" || type === "rental_97_5";
}

/**
 * 라벨에 1년 이내 재증액을 명시한다 — 엔진은 「있음」을 고른 경우에만 계약 이력을 받아 5%·1년 두 규정을 판정하므로,
 * 라벨이 「5% 증액 위반」뿐이면 5% 이내로 1년 안에 올린 사용자가 「없음」을 골라 1년 규정이 판정되지 않는다
 * (리뷰 게이트 2026-11-01 결함 2).
 */
export const RENT_INCREASE_VIOLATION_LABEL = "임대료 증액 위반 이력(5% 초과 또는 1년 이내 재증액)";

/** 섹션 제목의 근거 조문 — 종전에는 다섯 조문 폼이 모두 「§97의3①2호」를 달았다(리뷰 게이트 2026-11-01). */
export function rentIncreaseSectionTitle(type: string): string {
  switch (type) {
    case "rental_97_5":
      return "임대료 증액 제한 (§97의5①3호 → §97의3①2호)";
    case "rental_97_4":
      return "임대료 증액 제한 (소득세법 시행령 §167의3①2호)";
    default:
      return "임대료 증액 제한 (§97의3①2호)";
  }
}
