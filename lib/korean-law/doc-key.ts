/**
 * 해석례·결정례 문서번호 비교 키와 일자 정규화.
 *
 * 같은 문서라도 출처마다 표기가 다르다(2026-10-21 실측):
 *   카드(taxlaw 목록)  「서면-2016-법령해석재산-3189 [법령해석과-2507]」 · 「기획재정부 조세정책과-1199 [조세정책과-1199(2024.6.25.)]」
 *   taxlaw 상세        「서면-2016-법령해석재산-3189」 · 「기획재정부 조세정책과-1199」
 *   DRF 해석 검색      「사전-2025-법규재산-0190[법규과-1109]」 · 기재부는 접두사 없이 「조세정책과-1199」
 *   DRF 조세심판       「조심 2025중4302」  ↔  카드 「조심-2025-중-4302」
 * 비교는 반드시 이 키로만 한다 — 문자열을 그대로 비교하면 같은 문서가 다른 문서가 된다.
 */

/** `[…]` 꼬리 · 「기획재정부/재정경제부」 접두사 · 공백 · 하이픈을 지운 비교 키 */
export function docKey(docNo: string): string {
  return docNo
    .replace(/\[.*$/s, "") // 꼬리 안에 괄호·날짜가 또 들어 있다 — 첫 「[」부터 끝까지
    .replace(/^\s*(?:기획재정부|재정경제부)\s*/, "")
    .replace(/[\s-]/g, "");
}

/**
 * 일자 표기 통일 → 「YYYY.MM.DD.」(카드 표기). 해석할 수 없으면 null.
 *   DRF 「2026.06.08」 · 카드 「2016.03.31.」 · taxlaw 「20160331」 · 화면 「2016-03-31」
 */
export function docDate(raw: string | null | undefined): string | null {
  const m = (raw ?? "").trim().match(/^(\d{4})[.-]?(\d{2})[.-]?(\d{2})\.?$/);
  return m ? `${m[1]}.${m[2]}.${m[3]}.` : null;
}
